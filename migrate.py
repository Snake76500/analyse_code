# ANSI Terminal Colors
RESET = "\033[0m"
BOLD = "\033[1m"
GREEN = "\033[32m"
RED = "\033[31m"
YELLOW = "\033[33m"
BLUE = "\033[34m"
CYAN = "\033[36m"
MAGENTA = "\033[35m"

def colorize_diff(diff_str: str) -> str:
    """Add syntax colors to unified diff text."""
    colored_lines = []
    for line in diff_str.splitlines():
        if line.startswith("+++") or line.startswith("---"):
            colored_lines.append(f"{BOLD}{CYAN}{line}{RESET}")
        elif line.startswith("@@"):
            colored_lines.append(f"{MAGENTA}{line}{RESET}")
        elif line.startswith("+"):
            colored_lines.append(f"{GREEN}{line}{RESET}")
        elif line.startswith("-"):
            colored_lines.append(f"{RED}{line}{RESET}")
        else:
            colored_lines.append(line)
    return "\n".join(colored_lines)



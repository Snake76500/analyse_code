def main():
    parser = argparse.ArgumentParser(
        description="Outil de migration de code : remplace les appels aux microservices manuels par les microservices autogénérés."
    )
    parser.add_argument(
        "--target", "-t",
        required=True,
        help="Chemin vers le répertoire du projet ou code consommateur à migrer."
    )
    parser.add_argument(
        "--manual", "-m",
        required=True,
        help="Chemin vers le microservice développé manuellement."
    )
    parser.add_argument(
        "--autogen", "-a",
        required=True,
        help="Chemin vers le microservice autogénéré (OpenAPI/OpenAI)."
    )
    parser.add_argument(
        "--example", "-e",
        required=True,
        help="Chemin vers le fichier exemple de migration (.py avec blocs avant/après ou .diff/.patch)."
    )
    parser.add_argument(
        "--output", "-o",
        help="Chemin du répertoire de sortie où écrire le projet migré (ne modifie pas l'original)."
    )
    parser.add_argument(
        "--apply",
        action="store_true",
        help="Appliquer les modifications directement en place dans les fichiers cibles (crée des sauvegardes .bak)."
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Mode prévisualisation seule (affiche les diffs sans modifier aucun fichier). Actif par défaut si ni --apply ni --output n'est spécifié."
    )
    parser.add_argument(
        "--html",
        help="Chemin optionnel pour exporter un rapport HTML interactif des diffs."
    )
    parser.add_argument(
        "--json",
        help="Chemin optionnel pour exporter le rapport complet de migration en JSON."
    )

    args = parser.parse_args()

    # Validations
    if not os.path.exists(args.target):
        print(f"{RED}Erreur : Le répertoire cible '{args.target}' est introuvable.{RESET}", file=sys.stderr)
        sys.exit(1)
    if not os.path.exists(args.manual):
        print(f"{RED}Erreur : Le microservice manuel '{args.manual}' est introuvable.{RESET}", file=sys.stderr)
        sys.exit(1)
    if not os.path.exists(args.autogen):
        print(f"{RED}Erreur : Le microservice autogénéré '{args.autogen}' est introuvable.{RESET}", file=sys.stderr)
        sys.exit(1)
    if not os.path.exists(args.example):
        print(f"{RED}Erreur : Le fichier exemple '{args.example}' est introuvable.{RESET}", file=sys.stderr)
        sys.exit(1)

    # Determine execution mode
    dry_run = args.dry_run or (not args.apply and not args.output)
    mode_desc = "Prévisualisation seule (Dry-Run)" if dry_run else ("Modification en place (--apply)" if args.apply else f"Copie vers '{args.output}'")

    print(f"\n{BOLD}{CYAN}============================================================{RESET}")
    print(f"{BOLD}{CYAN}🚀 OUTIL DE MIGRATION DE CODE MICROSERVICES{RESET}")
    print(f"{BOLD}{CYAN}============================================================{RESET}")
    print(f"📂 Code à migrer       : {args.target}")
    print(f"📘 Microservice manuel : {args.manual}")
    print(f"📗 Microservice autogen: {args.autogen}")
    print(f"💡 Fichier exemple     : {args.example}")
    print(f"⚙️  Mode d'exécution    : {BOLD}{mode_desc}{RESET}")
    print(f"{CYAN}============================================================{RESET}\n")

    print("🔍 Analyse de la matrice de correspondance et extraction des règles d'exemple...")
    engine = CodeMigrationEngine(
        manual_service_path=args.manual,
        autogen_service_path=args.autogen,
        example_migration_path=args.example
    )

    print(f"   ➔ Classe manuelle détectée   : {BOLD}{engine.rule.manual_class_name}{RESET}")
    print(f"   ➔ Classe autogénérée cible   : {BOLD}{engine.rule.autogen_class_name}{RESET}")
    print(f"   ➔ Méthodes mappées            : {BOLD}{len(engine.rule.method_mappings)}{RESET}")

    print("\n⚡ Exécution de la migration sur le répertoire cible...")
    report = engine.migrate_directory(
        target_dir=args.target,
        output_dir=args.output,
        apply_in_place=args.apply
    )

    # Display per-file diffs
    print(f"\n{BOLD}{CYAN}============================================================{RESET}")
    print(f"{BOLD}DIFFS DE MIGRATION{RESET}")
    print(f"{BOLD}{CYAN}============================================================{RESET}")

    modified_files = [f for f in report.file_results if f.changes_count > 0]
    if not modified_files:
        print(f"{YELLOW}Aucun appel au microservice manuel n'a été détecté dans les fichiers analysés.{RESET}")
    else:
        for res in modified_files:
            print(f"\n{BOLD}📄 Fichier : {res.file_path}{RESET} ({GREEN}{res.changes_count} changement(s){RESET})")
            for rule in res.applied_rules:
                print(f"   {GREEN}✓{RESET} {rule}")
            if res.warnings:
                for w in res.warnings:
                    print(f"   {YELLOW}⚠️  {w}{RESET}")
            print("\n" + colorize_diff(res.diff))

    # Summary
    print(f"\n{BOLD}{CYAN}============================================================{RESET}")
    print(f"{BOLD}📊 RÉSUMÉ DE LA MIGRATION{RESET}")
    print(f"{BOLD}{CYAN}============================================================{RESET}")
    print(f"  • Fichiers Python analysés  : {report.total_files_scanned}")
    print(f"  • Fichiers impactés         : {BOLD}{GREEN if report.files_modified_count > 0 else RESET}{report.files_modified_count}{RESET}")
    print(f"  • Appels & paramètres migrés: {BOLD}{GREEN}{report.total_calls_migrated}{RESET}")

    if report.unmapped_calls:
        print(f"\n{YELLOW}⚠️  Endpoints manuels sans équivalent autogénéré :{RESET}")
        for u in report.unmapped_calls:
            print(f"   - {u}")

    if dry_run and report.files_modified_count > 0:
        print(f"\n{YELLOW}ℹ️  Mode prévisualisation : aucun fichier n'a été modifié.{RESET}")
        print(f"   Pour appliquer les changements, relancez avec {BOLD}--apply{RESET} ou {BOLD}--output <dossier>{RESET}.")
    elif args.apply:
        print(f"\n{GREEN}✅ Modifications appliquées avec succès ! (Fichiers de sauvegarde .bak créés){RESET}")
    elif args.output:
        print(f"\n{GREEN}✅ Projet migré généré avec succès dans : {os.path.abspath(args.output)}{RESET}")

    # Optional exports
    if args.html:
        html_content = generate_migration_html(report)
        with open(args.html, "w", encoding="utf-8") as f:
            f.write(html_content)
        print(f"✅ Rapport HTML interactif généré : {os.path.abspath(args.html)}")

    if args.json:
        with open(args.json, "w", encoding="utf-8") as f:
            f.write(json.dumps(report.to_dict(), indent=2, ensure_ascii=False))
        print(f"✅ Données JSON exportées : {os.path.abspath(args.json)}")

    print(f"{CYAN}============================================================{RESET}\n")

if __name__ == "__main__":
    main()

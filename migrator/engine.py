"""
Core Code Migration Engine.
Uses Endpoint & Parameter Correspondence Matrix and Example Migration Rules
to rewrite client consumer calls from manual microservices to autogenerated microservices.
"""
import ast
import os
import shutil
import difflib
from typing import List, Dict, Optional, Tuple, Set
from analyzer.parser import parse_service_directory, parse_python_file
from analyzer.matcher import match_microservices
from analyzer.models import EndpointMatch, AnalysisResult
from .models import MigrationRule, MethodMapping, FileMigrationResult, MigrationReport
from .example_parser import ExampleMigrationParser


class CodeMigrationEngine:
    def __init__(
        self,
        manual_service_path: str,
        autogen_service_path: str,
        example_migration_path: Optional[str] = None,
        example_content: Optional[str] = None
    ):
        self.manual_path = manual_service_path
        self.autogen_path = autogen_service_path
        self.example_path = example_migration_path or ""
        self.example_content = example_content or ""

        if not self.example_content and self.example_path and os.path.exists(self.example_path):
            with open(self.example_path, "r", encoding="utf-8", errors="replace") as f:
                self.example_content = f.read()

        # 1. Build Correspondence Matrix (manual: direct, autogen: parent resolution)
        manual_calls = parse_service_directory(self.manual_path, resolve_parents=False)
        autogen_calls = parse_service_directory(self.autogen_path, resolve_parents=True)
        self.matrix_result: AnalysisResult = match_microservices(
            manual_calls, autogen_calls, self.manual_path, self.autogen_path
        )

        # 2. Extract rules from example file
        self.rule = MigrationRule()
        if self.example_content:
            parser = ExampleMigrationParser(self.example_content)
            self.rule = parser.parse_rule()

        # 3. Augment / merge rules with Correspondence Matrix
        self._merge_matrix_into_rules()

    def _merge_matrix_into_rules(self):
        """Merge method and parameter correspondences from the matrix into migration rules."""
        for match in self.matrix_result.matches:
            if match.status != "MATCHED" or not match.manual_call or not match.autogen_call:
                continue

            manual_name = match.manual_call.function_name
            autogen_name = match.autogen_call.function_name
            if match.call_example and match.call_example.get("call_path"):
                autogen_name = f"{match.call_example['call_path']}.{autogen_name}"

            # Build parameter mapping
            param_map = {}
            deprecated_params = []
            for diff in match.param_diffs:
                if diff.status == "renamed_candidate":
                    # e.g., name is "user_id ➔ id"
                    if "➔" in diff.name:
                        parts = [p.strip() for p in diff.name.split("➔")]
                        if len(parts) == 2:
                            param_map[parts[0]] = parts[1]
                elif diff.status == "identical":
                    param_map[diff.name] = diff.name
                elif diff.status == "manual_only":
                    deprecated_params.append(diff.name)

            # Positional parameter index mapping
            positional_map = {}
            for idx, p in enumerate(match.manual_call.function_params):
                if p.name in param_map:
                    positional_map[idx] = param_map[p.name]
                elif idx < len(match.autogen_call.function_params):
                    positional_map[idx] = match.autogen_call.function_params[idx].name

            if manual_name not in self.rule.method_mappings:
                self.rule.method_mappings[manual_name] = MethodMapping(
                    manual_method=manual_name,
                    autogen_method=autogen_name,
                    param_map=param_map,
                    positional_map=positional_map,
                    deprecated_params=deprecated_params
                )
            else:
                # Merge into existing mapping from example if missing
                existing = self.rule.method_mappings[manual_name]
                if match.call_example and match.call_example.get("call_path"):
                    sub_prefix = match.call_example["call_path"] + "."
                    if not existing.autogen_method.startswith(sub_prefix):
                        existing.autogen_method = f"{sub_prefix}{match.autogen_call.function_name}"
                elif not existing.autogen_method:
                    existing.autogen_method = autogen_name
                for k, v in param_map.items():
                    if k not in existing.param_map:
                        existing.param_map[k] = v
                if not existing.positional_map:
                    existing.positional_map = positional_map

        # Ensure autogen_class_name uses SyncApiClient if available
        if not self.rule.autogen_class_name or self.rule.autogen_class_name == "AutogenApiClient":
            for match in self.matrix_result.matches:
                if match.call_example and match.call_example.get("class_name"):
                    if "sync" in match.call_example["class_name"].lower():
                        self.rule.autogen_class_name = match.call_example["class_name"]
                        break

    def migrate_source_code(self, source_code: str, file_path: str = "") -> FileMigrationResult:
        """
        Migrate a Python source code string from manual client calls to autogen client calls.
        Preserves original formatting, comments, and structure, supporting single-line and multiline calls.
        """
        lines = source_code.splitlines()
        applied_rules = []
        warnings = []
        changes_count = 0

        manual_class = self.rule.manual_class_name
        autogen_class = self.rule.autogen_class_name

        # Pass 1: Replace imports
        new_lines = []
        for line in lines:
            replaced = False
            for old_imp, new_imp in self.rule.import_replacements.items():
                if old_imp in line:
                    indent = line[:len(line) - len(line.lstrip())]
                    new_line = indent + new_imp
                    if new_line != line:
                        new_lines.append(new_line)
                        applied_rules.append(f"Import: '{old_imp}' ➔ '{new_imp}'")
                        changes_count += 1
                        replaced = True
                        break

            if replaced:
                continue

            if f"import {manual_class}" in line or f"import {manual_class} as" in line:
                line_migrated = line.replace(manual_class, autogen_class)
                new_lines.append(line_migrated)
                applied_rules.append(f"Import de classe: '{manual_class}' ➔ '{autogen_class}'")
                changes_count += 1
                continue

            new_lines.append(line)

        transformed_lines = list(new_lines)
        transformed_content = "\n".join(transformed_lines)

        # Pass 2: AST analysis for call sites and multiline ranges
        client_vars = {"client", "api_client", "service_client", "api", "manual_client"}
        call_transformations = []  # list of (start_line, end_line, type, data)

        try:
            tree = ast.parse(transformed_content)
            for node in ast.walk(tree):
                # Detect client assignments
                if isinstance(node, ast.Assign) and isinstance(node.value, ast.Call):
                    func_name = ""
                    if isinstance(node.value.func, ast.Name):
                        func_name = node.value.func.id
                    elif isinstance(node.value.func, ast.Attribute):
                        func_name = node.value.func.attr
                    if func_name in (manual_class, autogen_class):
                        for target in node.targets:
                            if isinstance(target, ast.Name):
                                client_vars.add(target.id)
                            elif isinstance(target, ast.Attribute):
                                client_vars.add(target.attr)

                # Detect Constructor Calls
                if isinstance(node, ast.Call):
                    c_name = ""
                    if isinstance(node.func, ast.Name):
                        c_name = node.func.id
                    elif isinstance(node.func, ast.Attribute):
                        c_name = node.func.attr

                    if c_name == manual_class:
                        start_l = node.lineno
                        end_l = getattr(node, "end_lineno", start_l)
                        call_transformations.append((start_l, end_l, "constructor", None))

                # Detect Method Calls
                if isinstance(node, ast.Call) and isinstance(node.func, ast.Attribute):
                    method_name = node.func.attr
                    if method_name in self.rule.method_mappings:
                        start_l = node.lineno
                        end_l = getattr(node, "end_lineno", start_l)
                        mapping = self.rule.method_mappings[method_name]
                        call_transformations.append((start_l, end_l, "method", mapping))
        except Exception as e:
            warnings.append(f"Analyse AST: {e}")

        # Pass 3: Apply transformations across detected line ranges
        # Sort transformations by start line
        call_transformations.sort(key=lambda x: x[0])

        # Track which lines belong to which call transformation
        for start_l, end_l, kind, mapping in call_transformations:
            start_idx = max(0, start_l - 1)
            end_idx = min(len(transformed_lines), end_l)

            if kind == "constructor":
                for idx in range(start_idx, end_idx):
                    line = transformed_lines[idx]
                    if manual_class in line:
                        line = line.replace(manual_class, autogen_class)
                        applied_rules.append(f"Instanciation: '{manual_class}' ➔ '{autogen_class}'")
                        changes_count += 1
                    for old_arg, new_arg in self.rule.constructor_param_map.items():
                        if f"{old_arg}=" in line:
                            line = line.replace(f"{old_arg}=", f"{new_arg}=")
                            applied_rules.append(f"Paramètre constructeur: '{old_arg}' ➔ '{new_arg}'")
                            changes_count += 1
                    transformed_lines[idx] = line

            elif kind == "method" and mapping:
                manual_method = mapping.manual_method
                autogen_method = mapping.autogen_method

                for idx in range(start_idx, end_idx):
                    line = transformed_lines[idx]

                    # Replace method name
                    pattern = f".{manual_method}("
                    if pattern in line:
                        line = line.replace(pattern, f".{autogen_method}(")
                        applied_rules.append(f"Appel de fonction: '{manual_method}()' ➔ '{autogen_method}()'")
                        changes_count += 1

                    # Replace keyword parameters across all lines of the call
                    for old_p, new_p in mapping.param_map.items():
                        if old_p != new_p and f"{old_p}=" in line:
                            line = line.replace(f"{old_p}=", f"{new_p}=")
                            applied_rules.append(f"Paramètre d'appel: '{old_p}=' ➔ '{new_p}=' dans {autogen_method}()")
                            changes_count += 1

                    # Check deprecated parameters
                    for dep_p in mapping.deprecated_params:
                        if f"{dep_p}=" in line:
                            warnings.append(
                                f"Paramètre '{dep_p}' dans '{manual_method}()' n'existe plus dans l'autogénéré '{autogen_method}()'."
                            )

                    transformed_lines[idx] = line

        migrated_content = "\n".join(transformed_lines)
        if source_code.endswith("\n"):
            migrated_content += "\n"

        # Generate Unified Diff
        diff_lines = list(difflib.unified_diff(
            source_code.splitlines(keepends=True),
            migrated_content.splitlines(keepends=True),
            fromfile=f"a/{file_path or 'source.py'}",
            tofile=f"b/{file_path or 'migrated.py'}",
            n=3
        ))
        diff_str = "".join(diff_lines)

        return FileMigrationResult(
            file_path=file_path,
            original_content=source_code,
            migrated_content=migrated_content,
            diff=diff_str,
            changes_count=changes_count,
            applied_rules=applied_rules,
            warnings=warnings
        )

    def migrate_directory(
        self,
        target_dir: str,
        output_dir: Optional[str] = None,
        apply_in_place: bool = False
    ) -> MigrationReport:
        """
        Recursively scan and migrate all Python files in target_dir.
        If apply_in_place is True, rewrites files with a .bak backup.
        If output_dir is given, copies project and writes migrated files there.
        Otherwise (dry-run), calculates diffs and report without writing.
        """
        target_dir = os.path.abspath(target_dir)
        file_results = []
        total_calls_migrated = 0
        files_modified = 0

        # If writing to a new output directory, copy existing project first
        if output_dir and not apply_in_place:
            output_dir = os.path.abspath(output_dir)
            if not os.path.exists(output_dir):
                os.makedirs(output_dir, exist_ok=True)

        for root, dirs, files in os.walk(target_dir):
            if any(skip in root for skip in ["__pycache__", ".venv", "venv", ".git", ".pytest_cache"]):
                continue

            for file in files:
                if file.endswith(".py"):
                    full_path = os.path.join(root, file)
                    rel_path = os.path.relpath(full_path, target_dir)

                    try:
                        with open(full_path, "r", encoding="utf-8", errors="replace") as f:
                            source = f.read()

                        result = self.migrate_source_code(source, rel_path)
                        if result.changes_count > 0:
                            files_modified += 1
                            total_calls_migrated += result.changes_count

                            # Apply changes if requested
                            if apply_in_place:
                                bak_path = full_path + ".bak"
                                shutil.copyfile(full_path, bak_path)
                                with open(full_path, "w", encoding="utf-8") as f:
                                    f.write(result.migrated_content)

                            if output_dir:
                                dest_path = os.path.join(output_dir, rel_path)
                                os.makedirs(os.path.dirname(dest_path), exist_ok=True)
                                with open(dest_path, "w", encoding="utf-8") as f:
                                    f.write(result.migrated_content)

                        elif output_dir:
                            # Copy unchanged file to output dir
                            dest_path = os.path.join(output_dir, rel_path)
                            os.makedirs(os.path.dirname(dest_path), exist_ok=True)
                            with open(dest_path, "w", encoding="utf-8") as f:
                                f.write(source)

                        file_results.append(result)
                    except Exception as e:
                        file_results.append(FileMigrationResult(
                            file_path=rel_path,
                            original_content="",
                            migrated_content="",
                            diff="",
                            changes_count=0,
                            warnings=[f"Impossible de traiter {rel_path}: {e}"]
                        ))

        # Check for any unmapped endpoints from manual microservice
        unmapped = []
        for m in self.matrix_result.matches:
            if m.status == "MANUAL_ONLY" and m.manual_call:
                unmapped.append(f"{m.manual_call.function_name}() [{m.http_method} {m.normalized_endpoint}]")

        return MigrationReport(
            target_dir=target_dir,
            manual_ref=self.manual_path,
            autogen_ref=self.autogen_path,
            example_ref=self.example_path,
            total_files_scanned=len(file_results),
            files_modified_count=files_modified,
            total_calls_migrated=total_calls_migrated,
            file_results=file_results,
            unmapped_calls=unmapped
        )

"""
Parser for autogenerated microservice dependency declaration files (*_dependency.py).
Understands class declarations, imports, and generates realistic code call examples.
"""
import ast
import os
import re
from dataclasses import dataclass, field
from typing import Dict, List, Optional, Any
from .models import EndpointCall, ParameterInfo


@dataclass
class ClassInstantiationInfo:
    class_name: str
    variable_name: str
    import_line: str
    instantiation_code: str
    constructor_kwargs: Dict[str, str] = field(default_factory=dict)
    source_file: str = ""


@dataclass
class DependencyContext:
    file_path: Optional[str] = None
    file_content: str = ""
    imports: List[str] = field(default_factory=list)
    import_modules: Dict[str, str] = field(default_factory=dict)  # Symbol -> "from module import Symbol"
    instantiations: Dict[str, ClassInstantiationInfo] = field(default_factory=dict)  # ClassName -> info
    factory_functions: Dict[str, str] = field(default_factory=dict)  # ClassName -> "get_client()"
    dependency_classes: List[str] = field(default_factory=list)


def find_dependency_file(dir_path: str) -> Optional[str]:
    """Find a Python file containing or ending with '_dependency' in dir_path."""
    if not os.path.exists(dir_path):
        return None

    if os.path.isfile(dir_path):
        if "_dependency" in os.path.basename(dir_path):
            return dir_path
        return None

    for root, _, files in os.walk(dir_path):
        if any(skip in root for skip in ["__pycache__", ".venv", "venv", ".git"]):
            continue
        for file in files:
            if file.endswith(".py") and ("_dependency" in file or file.startswith("dependency")):
                return os.path.join(root, file)

    return None


def find_dependency_in_memory(file_list: List[Dict[str, str]]) -> Optional[Dict[str, str]]:
    """Find a virtual file ending with '_dependency.py' in the in-memory upload list."""
    for item in file_list:
        path = item.get("path", "")
        if path.endswith(".py") and ("_dependency" in path or path.startswith("dependency")):
            return item
    return None


class DependencyFileVisitor(ast.NodeVisitor):
    def __init__(self, file_path: str, source_code: str):
        self.file_path = file_path
        self.source_code = source_code
        self.source_lines = source_code.splitlines()

        self.imports: List[str] = []
        self.import_modules: Dict[str, str] = {}  # Symbol -> import line
        self.instantiations: Dict[str, ClassInstantiationInfo] = {}  # ClassName -> Info
        self.factory_functions: Dict[str, str] = {}
        self.dependency_classes: List[str] = []

    def visit_Import(self, node: ast.Import):
        try:
            line = ast.unparse(node)
            self.imports.append(line)
            for alias in node.names:
                name = alias.asname or alias.name
                self.import_modules[name] = line
        except Exception:
            pass

    def visit_ImportFrom(self, node: ast.ImportFrom):
        try:
            line = ast.unparse(node)
            self.imports.append(line)
            for alias in node.names:
                name = alias.asname or alias.name
                self.import_modules[name] = line
        except Exception:
            pass

    def visit_ClassDef(self, node: ast.ClassDef):
        self.dependency_classes.append(node.name)
        # Inspect class body for assignments and __init__
        for item in node.body:
            if isinstance(item, ast.FunctionDef) and item.name == "__init__":
                self._inspect_init(node.name, item)
            elif isinstance(item, ast.AnnAssign) and isinstance(item.value, ast.Call):
                self._inspect_call_assign(item.target, item.value)
            elif isinstance(item, ast.Assign) and isinstance(item.value, ast.Call):
                for target in item.targets:
                    self._inspect_call_assign(target, item.value)
        self.generic_visit(node)

    def visit_FunctionDef(self, node: ast.FunctionDef):
        # Look for factory functions e.g. def get_client() -> AutogenApiClient: return AutogenApiClient(...)
        return_type = None
        if node.returns:
            try:
                return_type = ast.unparse(node.returns)
            except Exception:
                pass

        for stmt in node.body:
            if isinstance(stmt, ast.Return) and isinstance(stmt.value, ast.Call):
                func_name = self._get_call_name(stmt.value)
                target_class = return_type or func_name
                if target_class:
                    self.factory_functions[target_class] = f"{node.name}()"
                    self._inspect_call_assign(ast.Name(id="client", ctx=ast.Store()), stmt.value)

        self.generic_visit(node)

    def visit_Assign(self, node: ast.Assign):
        # Top-level assignment: client = AutogenApiClient(token="...")
        if isinstance(node.value, ast.Call):
            for target in node.targets:
                self._inspect_call_assign(target, node.value)
        self.generic_visit(node)

    def _inspect_init(self, enclosing_class: str, init_node: ast.FunctionDef):
        for stmt in init_node.body:
            if isinstance(stmt, ast.Assign) and isinstance(stmt.value, ast.Call):
                for target in stmt.targets:
                    self._inspect_call_assign(target, stmt.value)

    def _get_call_name(self, call_node: ast.Call) -> str:
        try:
            return ast.unparse(call_node.func)
        except Exception:
            return ""

    def _inspect_call_assign(self, target_node: ast.AST, call_node: ast.Call):
        class_name = self._get_call_name(call_node)
        # Handle self.client or client
        var_name = "client"
        try:
            target_str = ast.unparse(target_node)
            if target_str.startswith("self."):
                var_name = target_str.replace("self.", "")
            else:
                var_name = target_str
        except Exception:
            pass

        kwargs = {}
        for kw in call_node.keywords:
            if kw.arg:
                try:
                    kwargs[kw.arg] = ast.unparse(kw.value)
                except Exception:
                    kwargs[kw.arg] = "..."

        try:
            call_code = ast.unparse(call_node)
        except Exception:
            args_str = ", ".join([f"{k}={v}" for k, v in kwargs.items()])
            call_code = f"{class_name}({args_str})"

        import_line = self.import_modules.get(class_name, "")
        if not import_line:
            # Fallback if class is imported
            for sym, imp in self.import_modules.items():
                if sym == class_name:
                    import_line = imp
                    break

        self.instantiations[class_name] = ClassInstantiationInfo(
            class_name=class_name,
            variable_name=var_name,
            import_line=import_line,
            instantiation_code=f"{var_name} = {call_code}",
            constructor_kwargs=kwargs,
            source_file=self.file_path
        )


def parse_dependency_content(content: str, file_path: str = "dependency.py") -> DependencyContext:
    """Parse the AST of a dependency declaration file."""
    ctx = DependencyContext(file_path=file_path, file_content=content)
    try:
        tree = ast.parse(content, filename=file_path)
        visitor = DependencyFileVisitor(file_path, content)
        visitor.visit(tree)

        ctx.imports = visitor.imports
        ctx.import_modules = visitor.import_modules
        ctx.instantiations = visitor.instantiations
        ctx.factory_functions = visitor.factory_functions
        ctx.dependency_classes = visitor.dependency_classes
    except Exception as e:
        print(f"Warning: could not parse dependency file {file_path}: {e}")

    return ctx


def parse_dependency_file(file_path: str) -> Optional[DependencyContext]:
    """Parse a dependency file from disk."""
    if not os.path.exists(file_path):
        return None
    try:
        with open(file_path, "r", encoding="utf-8", errors="replace") as f:
            content = f.read()
        return parse_dependency_content(content, file_path)
    except Exception as e:
        print(f"Warning: could not read {file_path}: {e}")
        return None


def format_example_value(param: ParameterInfo) -> str:
    """Generate a realistic, syntactically valid Python value for a parameter."""
    name = param.name.lower()
    type_ann = (param.type_annotation or "").lower()

    # Name-based heuristic overrides
    if name in {"id", "user_id", "customer_id", "item_id", "order_id"}:
        if "str" in type_ann:
            return '"usr_101"'
        return "101"
    if name in {"token", "api_key", "key", "auth", "secret"}:
        return '"your_api_token_here"'
    if name in {"voucher", "promo_code", "discount_code", "coupon"}:
        return '"SPRING10"'
    if name in {"q", "query", "search", "keyword"}:
        return '"winter jackets"'
    if name in {"limit", "page_size", "count", "max_results"}:
        return "25"
    if name in {"offset", "skip", "page"}:
        return "0"
    if name in {"quantity", "qty", "stock"}:
        return "100"
    if name in {"currency"}:
        return '"EUR"'
    if name in {"date", "start_date", "end_date", "timestamp"}:
        return '"2026-10-15"'
    if name in {"email"}:
        return '"user@example.com"'
    if name in {"view_id"}:
        return '"overview"'
    if name in {"product_id"}:
        return "55"
    if name in {"purge_data", "include_billing", "is_active", "expand", "force"}:
        return "True"
    if name in {"items", "cart", "products"}:
        return '[{"item_id": 1, "qty": 2}]'
    if name in {"payload", "data", "body"}:
        return '{"name": "Sample Order", "status": "pending"}'

    # Type-based heuristic
    if "int" in type_ann:
        return param.default_value if param.default_value and param.default_value != "None" else "42"
    if "float" in type_ann:
        return param.default_value if param.default_value and param.default_value != "None" else "19.99"
    if "bool" in type_ann:
        return param.default_value if param.default_value and param.default_value != "None" else "True"
    if "list" in type_ann:
        if param.default_value and param.default_value not in ("None", "[]"):
            return param.default_value
        return '["item_1", "item_2"]'
    if "dict" in type_ann:
        if param.default_value and param.default_value not in ("None", "{}"):
            return param.default_value
        return '{"key": "value"}'
    if "str" in type_ann:
        if param.default_value and param.default_value != "None":
            return param.default_value
        return f'"{name}_val"'

    # Default value fallback
    if param.default_value and param.default_value != "None":
        return param.default_value

    return f'"{name}_sample"'


def generate_function_call_example(
    call: EndpointCall,
    dependency_ctx: Optional[DependencyContext] = None,
    service_root_path: str = ""
) -> Dict[str, Any]:
    """
    Generate an example of function call with all required imports and class instantiation
    based on the dependency declaration file.
    """
    func_name = call.function_name
    class_name = call.class_name or "AutogenApiClient"
    file_path = call.file_path or "service.py"
    dep_file = dependency_ctx.file_path if dependency_ctx else None

    # 1. Determine Import Statements
    imports = []
    class_instantiation = ""
    var_name = "client"

    if dependency_ctx and class_name in dependency_ctx.instantiations:
        info = dependency_ctx.instantiations[class_name]
        var_name = info.variable_name or "client"
        if info.import_line:
            imports.append(info.import_line)
        class_instantiation = info.instantiation_code
    elif dependency_ctx and dependency_ctx.instantiations:
        # Pick the first available instantiation if class name differs slightly
        first_info = next(iter(dependency_ctx.instantiations.values()))
        var_name = first_info.variable_name or "client"
        if first_info.import_line:
            imports.append(first_info.import_line)
        class_instantiation = first_info.instantiation_code
    else:
        # Fallback to standard module import if no dependency file was provided
        mod_name = os.path.splitext(os.path.basename(file_path))[0]
        if service_root_path:
            pkg_name = os.path.basename(os.path.normpath(service_root_path))
            import_str = f"from {pkg_name}.{mod_name} import {class_name}"
        else:
            import_str = f"from {mod_name} import {class_name}"
        imports.append(import_str)
        class_instantiation = f"{var_name} = {class_name}(token=\"YOUR_API_TOKEN\")"

    # Add helper imports if factory function exists
    if dependency_ctx and class_name in dependency_ctx.factory_functions:
        factory_name = dependency_ctx.factory_functions[class_name]
        class_instantiation = f"# Option via fabrique:\n{var_name} = {factory_name}\n# Ou instanciation directe:\n{class_instantiation}"

    # Check parameter types and add typing imports if needed
    needed_types = []
    for p in call.function_params:
        ann = p.type_annotation or ""
        for t in ["List", "Dict", "Optional", "Any", "Union"]:
            if t in ann and t not in needed_types:
                needed_types.append(t)
    if needed_types:
        imports.insert(0, f"from typing import {', '.join(needed_types)}")

    # 2. Build Call Parameters Example
    call_args = []
    for p in call.function_params:
        if p.name in ("self", "cls"):
            continue
        val = format_example_value(p)
        call_args.append(f"{p.name}={val}")

    if len(call_args) <= 2 and sum(len(a) for a in call_args) < 50:
        call_str = f"response = {var_name}.{func_name}({', '.join(call_args)})"
    else:
        formatted_args = ",\n    ".join(call_args)
        call_str = f"response = {var_name}.{func_name}(\n    {formatted_args}\n)"

    # 3. Assemble Complete Snippet
    snippet_parts = [
        "# ==================================================",
        f"# Exemple d'appel pour la fonction: {func_name}()",
        f"# Endpoint: [{call.http_method}] {call.normalized_endpoint}",
    ]
    if dep_file:
        snippet_parts.append(f"# Basé sur: {os.path.basename(dep_file)}")
    snippet_parts.append("# ==================================================\n")

    snippet_parts.append("# 1. Imports nécessaires")
    snippet_parts.extend(imports)
    snippet_parts.append("\n# 2. Initialisation de la dépendance")
    snippet_parts.append(class_instantiation)
    snippet_parts.append("\n# 3. Appel de la fonction du microservice autogénéré")
    snippet_parts.append(call_str)
    snippet_parts.append("print(f\"Résultat reçu: {response}\")")

    full_code = "\n".join(snippet_parts)

    return {
        "function_name": func_name,
        "class_name": class_name,
        "variable_name": var_name,
        "dependency_file": os.path.basename(dep_file) if dep_file else None,
        "imports": imports,
        "instantiation": class_instantiation,
        "call_snippet": call_str,
        "full_code": full_code
    }

"""
Parser for autogenerated microservice dependency declaration files (*_dependency.py).
Understands class declarations, imports, and generates realistic code call examples.
"""
import ast
import os
import re
from dataclasses import dataclass, field
from typing import Dict, List, Optional, Any, Set, Tuple
from .models import EndpointCall, ParameterInfo


@dataclass
class ClassInstantiationInfo:
    class_name: str
    variable_name: str
    import_line: str
    instantiation_code: str
    constructor_kwargs: Dict[str, str] = field(default_factory=dict)
    source_file: str = ""
    enclosing_class: Optional[str] = None
    is_manual: bool = False
    is_autogen: bool = False


@dataclass
class DependencyContext:
    file_path: Optional[str] = None
    file_content: str = ""
    imports: List[str] = field(default_factory=list)
    import_modules: Dict[str, str] = field(default_factory=dict)  # Symbol -> "from module import Symbol"
    instantiations: Dict[str, ClassInstantiationInfo] = field(default_factory=dict)  # ClassName -> info
    instantiations_list: List[ClassInstantiationInfo] = field(default_factory=list)
    factory_functions: Dict[str, str] = field(default_factory=dict)  # ClassName -> "get_client()"
    dependency_classes: List[str] = field(default_factory=list)


def extract_service_stem_from_dependency_path(file_path: str) -> Optional[str]:
    """
    Extract the homonym target service stem from a dependency file path.
    Example:
      'fichiera_dependency.py' -> 'fichiera'
      'controllers/users_dependency.py' -> 'users'
      'service_dependency.py' -> 'service'
    """
    if not file_path:
        return None
    base = os.path.basename(file_path)
    if not base.endswith(".py"):
        return None
    name_without_ext = base[:-3]
    if name_without_ext.endswith("_dependency"):
        return name_without_ext[:-len("_dependency")]
    if name_without_ext.endswith("_dependencies"):
        return name_without_ext[:-len("_dependencies")]
    if name_without_ext.endswith("-dependency"):
        return name_without_ext[:-len("-dependency")]
    if name_without_ext.endswith("-dependencies"):
        return name_without_ext[:-len("-dependencies")]
    return None


def build_dependency_registry_from_directory(dir_path: str) -> Dict[str, DependencyContext]:
    """
    Discover and parse all *_dependency.py files in a directory.
    Maps homonym_stem (lower-cased) -> DependencyContext.
    Enforces strict 1-to-1 homonym binding:
    fichiera.py is linked ONLY to fichiera_dependency.py.
    """
    registry: Dict[str, DependencyContext] = {}
    if not os.path.exists(dir_path):
        return registry

    if os.path.isfile(dir_path):
        stem = extract_service_stem_from_dependency_path(dir_path)
        if stem:
            ctx = parse_dependency_file(dir_path)
            if ctx:
                registry[stem.lower()] = ctx
        return registry

    for root, _, files in os.walk(dir_path):
        if any(skip in root for skip in ["__pycache__", ".venv", "venv", ".git"]):
            continue
        for file in files:
            if file.endswith(".py"):
                stem = extract_service_stem_from_dependency_path(file)
                if stem:
                    full_path = os.path.join(root, file)
                    ctx = parse_dependency_file(full_path)
                    if ctx:
                        registry[stem.lower()] = ctx
                        # Also key by relative path stem
                        rel_path = os.path.relpath(full_path, dir_path)
                        rel_stem = extract_service_stem_from_dependency_path(rel_path)
                        if rel_stem:
                            registry[rel_stem.lower()] = ctx

    return registry


def build_dependency_registry_from_memory(file_list: List[Dict[str, str]]) -> Dict[str, DependencyContext]:
    """
    Discover and parse all *_dependency.py files in an in-memory virtual file list.
    Maps homonym_stem (lower-cased) -> DependencyContext.
    """
    registry: Dict[str, DependencyContext] = {}
    for item in file_list:
        path = item.get("path", "")
        content = item.get("content", "")
        if path.endswith(".py") and content:
            stem = extract_service_stem_from_dependency_path(path)
            if stem:
                ctx = parse_dependency_content(content, path)
                registry[stem.lower()] = ctx
    return registry


def get_homonym_dependency(
    source_file_path: Optional[str],
    registry: Dict[str, DependencyContext]
) -> Optional[DependencyContext]:
    """
    Retrieve the dependency context uniquely linked to its homonym service file.
    Rule: fichiera.py can ONLY be linked to fichiera_dependency.py.
    """
    if not source_file_path or not registry:
        return None

    # Base stem from the service file: e.g. "fichiera.py" -> "fichiera"
    base_file = os.path.basename(source_file_path)
    stem = os.path.splitext(base_file)[0].lower()

    if stem in registry:
        return registry[stem]

    # Check relative path stem if available (e.g. "controllers/fichiera")
    norm_path = os.path.normpath(source_file_path).replace("\\", "/")
    rel_stem = os.path.splitext(norm_path)[0].lower()
    if rel_stem in registry:
        return registry[rel_stem]

    # No homonym dependency file exists for this service file
    return None


def find_dependency_file(dir_path: str) -> Optional[str]:
    """Find a Python file containing or ending with '_dependency' in dir_path."""
    if not os.path.exists(dir_path):
        return None

    if os.path.isfile(dir_path):
        if "_dependency" in os.path.basename(dir_path):
            return dir_path
        return None

    for root, _, files in os.walk(dir_path):
        if any(skip in root for skip in ["__pycache__", ".venv", "venv", ".git"]):
            continue
        for file in files:
            if file.endswith(".py") and ("_dependency" in file or file.startswith("dependency")):
                return os.path.join(root, file)

    return None


def find_dependency_in_memory(file_list: List[Dict[str, str]]) -> Optional[Dict[str, str]]:
    """Find a virtual file ending with '_dependency.py' in the in-memory upload list."""
    for item in file_list:
        path = item.get("path", "")
        if path.endswith(".py") and ("_dependency" in path or path.startswith("dependency")):
            return item
    return None


class DependencyFileVisitor(ast.NodeVisitor):
    def __init__(self, file_path: str, source_code: str):
        self.file_path = file_path
        self.source_code = source_code
        self.source_lines = source_code.splitlines()

        self.imports: List[str] = []
        self.import_modules: Dict[str, str] = {}  # Symbol -> import line
        self.instantiations: Dict[str, ClassInstantiationInfo] = {}  # ClassName -> Info
        self.instantiations_list: List[ClassInstantiationInfo] = []
        self.factory_functions: Dict[str, str] = {}
        self.dependency_classes: List[str] = []

    def visit_Import(self, node: ast.Import):
        try:
            line = ast.unparse(node)
            self.imports.append(line)
            for alias in node.names:
                name = alias.asname or alias.name
                self.import_modules[name] = line
        except Exception:
            pass

    def visit_ImportFrom(self, node: ast.ImportFrom):
        try:
            line = ast.unparse(node)
            self.imports.append(line)
            for alias in node.names:
                name = alias.asname or alias.name
                self.import_modules[name] = line
        except Exception:
            pass

    def visit_ClassDef(self, node: ast.ClassDef):
        self.dependency_classes.append(node.name)
        # Inspect class body for assignments, __init__, and getter methods
        for item in node.body:
            if isinstance(item, ast.FunctionDef) and item.name == "__init__":
                self._inspect_init(node.name, item)
            elif isinstance(item, ast.FunctionDef) and item.name != "__init__":
                self._inspect_method(node.name, item)
            elif isinstance(item, ast.AnnAssign) and isinstance(item.value, ast.Call):
                self._inspect_call_assign(item.target, item.value, enclosing_class=node.name)
            elif isinstance(item, ast.Assign) and isinstance(item.value, ast.Call):
                for target in item.targets:
                    self._inspect_call_assign(target, item.value, enclosing_class=node.name)
        self.generic_visit(node)

    def visit_FunctionDef(self, node: ast.FunctionDef):
        # Look for factory functions e.g. def get_client() -> AutogenApiClient: return AutogenApiClient(...)
        return_type = None
        if node.returns:
            try:
                return_type = ast.unparse(node.returns)
            except Exception:
                pass

        for stmt in node.body:
            if isinstance(stmt, ast.Return) and isinstance(stmt.value, ast.Call):
                func_name = self._get_call_name(stmt.value)
                target_class = return_type or func_name
                if target_class:
                    self.factory_functions[target_class] = f"{node.name}()"
                    self._inspect_call_assign(ast.Name(id="client", ctx=ast.Store()), stmt.value)

        self.generic_visit(node)

    def visit_Assign(self, node: ast.Assign):
        # Top-level assignment: client = AutogenApiClient(token="...")
        if isinstance(node.value, ast.Call):
            for target in node.targets:
                self._inspect_call_assign(target, node.value)
        self.generic_visit(node)

    def _inspect_init(self, enclosing_class: str, init_node: ast.FunctionDef):
        for stmt in init_node.body:
            if isinstance(stmt, ast.Assign) and isinstance(stmt.value, ast.Call):
                for target in stmt.targets:
                    self._inspect_call_assign(target, stmt.value, enclosing_class=enclosing_class)

    def _inspect_method(self, enclosing_class: str, func_node: ast.FunctionDef):
        return_type = None
        if func_node.returns:
            try:
                return_type = ast.unparse(func_node.returns)
            except Exception:
                pass

        for stmt in func_node.body:
            if isinstance(stmt, ast.Return):
                if isinstance(stmt.value, ast.Call):
                    func_name = self._get_call_name(stmt.value)
                    target_class = return_type or func_name
                    if target_class:
                        self.factory_functions[target_class] = f"{enclosing_class}().{func_node.name}()"
                elif isinstance(stmt.value, ast.Attribute) and return_type:
                    self.factory_functions[return_type] = f"{enclosing_class}().{func_node.name}()"

    def _get_call_name(self, call_node: ast.Call) -> str:
        try:
            return ast.unparse(call_node.func)
        except Exception:
            return ""

    def _inspect_call_assign(self, target_node: ast.AST, call_node: ast.Call, enclosing_class: str = ""):
        class_name = self._get_call_name(call_node)
        # Handle self.client or client
        var_name = "client"
        try:
            target_str = ast.unparse(target_node)
            if target_str.startswith("self."):
                var_name = target_str.replace("self.", "")
            else:
                var_name = target_str
        except Exception:
            pass

        kwargs = {}
        for kw in call_node.keywords:
            if kw.arg:
                try:
                    kwargs[kw.arg] = ast.unparse(kw.value)
                except Exception:
                    kwargs[kw.arg] = "..."

        try:
            call_code = ast.unparse(call_node)
        except Exception:
            args_str = ", ".join([f"{k}={v}" for k, v in kwargs.items()])
            call_code = f"{class_name}({args_str})"

        import_line = self.import_modules.get(class_name, "")
        if not import_line:
            # Fallback if class is imported
            for sym, imp in self.import_modules.items():
                if sym == class_name or sym == class_name.split(".")[-1]:
                    import_line = imp
                    break

        lower_check = f"{class_name} {var_name} {import_line} {enclosing_class}".lower()
        is_manual = any(kw in lower_check for kw in ["manual", "legacy", "old", "v1", "ancient", "deprecated"])
        is_autogen = any(kw in lower_check for kw in ["autogen", "auto", "openapi", "swagger", "generated"])

        info = ClassInstantiationInfo(
            class_name=class_name,
            variable_name=var_name,
            import_line=import_line,
            instantiation_code=f"{var_name} = {call_code}",
            constructor_kwargs=kwargs,
            source_file=self.file_path,
            enclosing_class=enclosing_class,
            is_manual=is_manual,
            is_autogen=is_autogen
        )
        self.instantiations[class_name] = info
        self.instantiations_list.append(info)


def parse_dependency_content(content: str, file_path: str = "dependency.py") -> DependencyContext:
    """Parse the AST of a dependency declaration file."""
    ctx = DependencyContext(file_path=file_path, file_content=content)
    try:
        tree = ast.parse(content, filename=file_path)
        visitor = DependencyFileVisitor(file_path, content)
        visitor.visit(tree)

        ctx.imports = visitor.imports
        ctx.import_modules = visitor.import_modules
        ctx.instantiations = visitor.instantiations
        ctx.instantiations_list = visitor.instantiations_list
        ctx.factory_functions = visitor.factory_functions
        ctx.dependency_classes = visitor.dependency_classes
    except Exception as e:
        print(f"Warning: could not parse dependency file {file_path}: {e}")

    return ctx


def parse_dependency_file(file_path: str) -> Optional[DependencyContext]:
    """Parse a dependency file from disk."""
    if not os.path.exists(file_path):
        return None
    try:
        with open(file_path, "r", encoding="utf-8", errors="replace") as f:
            content = f.read()
        return parse_dependency_content(content, file_path)
    except Exception as e:
        print(f"Warning: could not read {file_path}: {e}")
        return None


def format_example_value(param: ParameterInfo) -> str:
    """Generate a realistic, syntactically valid Python value for a parameter."""
    name = param.name.lower()
    type_ann = (param.type_annotation or "").lower()

    # Name-based heuristic overrides
    if name in {"id", "user_id", "customer_id", "item_id", "order_id"}:
        if "str" in type_ann:
            return '"usr_101"'
        return "101"
    if name in {"token", "api_key", "key", "auth", "secret"}:
        return '"your_api_token_here"'
    if name in {"voucher", "promo_code", "discount_code", "coupon"}:
        return '"SPRING10"'
    if name in {"q", "query", "search", "keyword"}:
        return '"winter jackets"'
    if name in {"limit", "page_size", "count", "max_results"}:
        return "25"
    if name in {"offset", "skip", "page"}:
        return "0"
    if name in {"quantity", "qty", "stock"}:
        return "100"
    if name in {"currency"}:
        return '"EUR"'
    if name in {"date", "start_date", "end_date", "timestamp"}:
        return '"2026-10-15"'
    if name in {"email"}:
        return '"user@example.com"'
    if name in {"view_id"}:
        return '"overview"'
    if name in {"product_id"}:
        return "55"
    if name in {"purge_data", "include_billing", "is_active", "expand", "force"}:
        return "True"
    if name in {"items", "cart", "products"}:
        return '[{"item_id": 1, "qty": 2}]'
    if name in {"payload", "data", "body"}:
        return '{"name": "Sample Order", "status": "pending"}'

    # Type-based heuristic
    if "int" in type_ann:
        return param.default_value if param.default_value and param.default_value != "None" else "42"
    if "float" in type_ann:
        return param.default_value if param.default_value and param.default_value != "None" else "19.99"
    if "bool" in type_ann:
        return param.default_value if param.default_value and param.default_value != "None" else "True"
    if "list" in type_ann:
        if param.default_value and param.default_value not in ("None", "[]"):
            return param.default_value
        return '["item_1", "item_2"]'
    if "dict" in type_ann:
        if param.default_value and param.default_value not in ("None", "{}"):
            return param.default_value
        return '{"key": "value"}'
    if "str" in type_ann:
        if param.default_value and param.default_value != "None":
            return param.default_value
        return f'"{name}_val"'

    # Default value fallback
    if param.default_value and param.default_value != "None":
        return param.default_value

    return f'"{name}_sample"'


def is_manual_dependency(info: ClassInstantiationInfo, manual_service_path: str = "") -> bool:
    """
    Check if a dependency instantiation belongs to the manual microservice.
    """
    if info.is_manual:
        return True

    lower_class = info.class_name.lower()
    lower_var = info.variable_name.lower()
    lower_import = (info.import_line or "").lower()

    for kw in ["manual", "legacy", "old", "v1", "ancient", "deprecated"]:
        if kw in lower_class or kw in lower_var or kw in lower_import:
            return True

    if manual_service_path:
        base_manual = os.path.basename(os.path.normpath(manual_service_path)).lower()
        if base_manual and base_manual in lower_import:
            return True

    return False


def is_autogen_dependency(
    info: ClassInstantiationInfo,
    target_class_name: Optional[str] = None,
    target_function_name: Optional[str] = None,
    service_file_stem: Optional[str] = None,
    autogen_service_path: str = ""
) -> bool:
    """
    Check if a dependency instantiation belongs to the autogenerated microservice.
    """
    if is_manual_dependency(info, ""):
        return False

    if info.is_autogen:
        return True

    lower_class = info.class_name.lower()
    lower_var = info.variable_name.lower()
    lower_import = (info.import_line or "").lower()

    if target_class_name:
        target_lower = target_class_name.lower()
        if lower_class == target_lower or lower_class.split(".")[-1] == target_lower:
            return True

    for kw in ["autogen", "auto", "openapi", "swagger", "generated"]:
        if kw in lower_class or kw in lower_var or kw in lower_import:
            return True

    if service_file_stem and service_file_stem.lower() in lower_import:
        return True

    if autogen_service_path:
        base_autogen = os.path.basename(os.path.normpath(autogen_service_path)).lower()
        if base_autogen and base_autogen in lower_import:
            return True

    return False


def build_class_method_index(
    dir_path: str = "",
    file_list: Optional[List[Dict[str, str]]] = None,
    calls: Optional[List[EndpointCall]] = None
) -> Dict[str, Set[str]]:
    """
    Build a comprehensive index of class_name (lowercased and original) -> set of methods
    defined in that class across all autogenerated microservice files.
    """
    index: Dict[str, Set[str]] = {}

    def _add_method(cls_name: str, m_name: str):
        if not cls_name or not m_name:
            return
        cls_low = cls_name.lower()
        if cls_low not in index:
            index[cls_low] = set()
        index[cls_low].add(m_name)
        if cls_name not in index:
            index[cls_name] = set()
        index[cls_name].add(m_name)
        base = cls_name.split(".")[-1]
        base_low = base.lower()
        if base_low not in index:
            index[base_low] = set()
        index[base_low].add(m_name)

    # 1. Index from existing parsed EndpointCalls
    if calls:
        for c in calls:
            if c.class_name and c.function_name:
                _add_method(c.class_name, c.function_name)
            if c.class_name and c.callee_function:
                _add_method(c.class_name, c.callee_function)

    # 2. Index from virtual file list
    def _parse_and_index_code(code: str, fname: str = ""):
        try:
            tree = ast.parse(code, filename=fname)
            for node in ast.walk(tree):
                if isinstance(node, ast.ClassDef):
                    for item in node.body:
                        if isinstance(item, (ast.FunctionDef, ast.AsyncFunctionDef)):
                            _add_method(node.name, item.name)
        except Exception:
            pass

    if file_list:
        for item in file_list:
            path = item.get("path", "")
            content = item.get("content", "")
            if path.endswith(".py") and content and not path.endswith("_dependency.py") and not path.endswith("_dependencies.py"):
                _parse_and_index_code(content, path)

    # 3. Index from directory path
    if dir_path and os.path.exists(dir_path):
        if os.path.isfile(dir_path):
            if not dir_path.endswith("_dependency.py") and not dir_path.endswith("_dependencies.py"):
                try:
                    with open(dir_path, "r", encoding="utf-8", errors="replace") as f:
                        _parse_and_index_code(f.read(), dir_path)
                except Exception:
                    pass
        else:
            for root, _, files in os.walk(dir_path):
                if any(skip in root for skip in ["__pycache__", ".venv", "venv", ".git"]):
                    continue
                for file in files:
                    if file.endswith(".py") and not file.endswith("_dependency.py") and not file.endswith("_dependencies.py"):
                        full_path = os.path.join(root, file)
                        try:
                            with open(full_path, "r", encoding="utf-8", errors="replace") as f:
                                _parse_and_index_code(f.read(), full_path)
                        except Exception:
                            pass

    return index


def reverse_engineer_autogen_dependency(
    call: EndpointCall,
    dependency_ctx: DependencyContext,
    class_method_index: Dict[str, Set[str]],
    manual_service_path: str = "",
    known_manual_classes: Optional[Set[str]] = None,
    service_root_path: str = ""
) -> Tuple[Optional[ClassInstantiationInfo], str]:
    """
    Reverse engineering to find the exact dependency linked to the autogenerated function:
    1. Identify all candidate source classes in the autogenerated microservice that define or implement call.function_name.
    2. Check which candidate in _dependency.py provides/instantiates that specific class.
    3. Verify method existence on candidates.
    4. Reject any dependency associated with the manual microservice.
    """
    known_manual = set(known_manual_classes or [])

    # Filter out all manual dependencies from dependency_ctx
    raw_candidates = dependency_ctx.instantiations_list or list(dependency_ctx.instantiations.values())
    valid_candidates: List[ClassInstantiationInfo] = []
    for info in raw_candidates:
        if info.class_name in known_manual or is_manual_dependency(info, manual_service_path):
            continue
        valid_candidates.append(info)

    if not valid_candidates:
        return None, call.class_name or "AutogenApiClient"

    func_name = call.function_name
    callee_name = call.callee_function

    # 1. Reverse-Engineering Step 1: Find all classes in autogenerated microservice
    # that define func_name or callee_name
    candidate_source_classes = set()
    if call.class_name:
        candidate_source_classes.add(call.class_name.lower())
        candidate_source_classes.add(call.class_name.split(".")[-1].lower())

    for cls_name, methods in class_method_index.items():
        if func_name in methods:
            candidate_source_classes.add(cls_name.lower())
            candidate_source_classes.add(cls_name.split(".")[-1].lower())
        if callee_name and callee_name in methods:
            candidate_source_classes.add(cls_name.lower())
            candidate_source_classes.add(cls_name.split(".")[-1].lower())
        for m in call.caller_chain:
            if m in methods:
                candidate_source_classes.add(cls_name.lower())
                candidate_source_classes.add(cls_name.split(".")[-1].lower())

    # 2. Reverse-Engineering Step 2: Check AST of call.file_path if available
    # to see which class encloses func_name or is instantiated inside func_name
    file_path = call.file_path
    if file_path:
        full_file_path = file_path
        if service_root_path and not os.path.isabs(file_path):
            candidate_full = os.path.join(service_root_path, file_path)
            if os.path.exists(candidate_full):
                full_file_path = candidate_full

        if os.path.exists(full_file_path) and os.path.isfile(full_file_path):
            try:
                with open(full_file_path, "r", encoding="utf-8", errors="replace") as f:
                    tree = ast.parse(f.read(), filename=full_file_path)
                for node in ast.walk(tree):
                    if isinstance(node, ast.ClassDef):
                        for item in node.body:
                            if isinstance(item, (ast.FunctionDef, ast.AsyncFunctionDef)):
                                if item.name in (func_name, callee_name):
                                    candidate_source_classes.add(node.name.lower())
                                    candidate_source_classes.add(node.name.split(".")[-1].lower())
                    elif isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                        if node.name in (func_name, callee_name):
                            # Inspect calls inside function body
                            for subnode in ast.walk(node):
                                if isinstance(subnode, ast.Call):
                                    func_id = None
                                    if isinstance(subnode.func, ast.Name):
                                        func_id = subnode.func.id
                                    elif isinstance(subnode.func, ast.Attribute):
                                        func_id = subnode.func.attr
                                    if func_id:
                                        if func_id.lower() in class_method_index:
                                            candidate_source_classes.add(func_id.lower())
                                            candidate_source_classes.add(func_id.split(".")[-1].lower())
            except Exception:
                pass

    # 3. Reverse-Engineering Step 3: Match source classes against valid candidates in _dependency.py
    # Priority 3A: Candidate in _dependency.py that directly instantiates one of the candidate source classes
    if candidate_source_classes:
        for info in valid_candidates:
            c_name_low = info.class_name.lower()
            c_base_low = info.class_name.split(".")[-1].lower()
            if c_name_low in candidate_source_classes or c_base_low in candidate_source_classes:
                return info, info.class_name

        for info in valid_candidates:
            for sc in candidate_source_classes:
                if re.search(r'\b' + re.escape(sc) + r'\b', info.import_line.lower()):
                    return info, info.class_name

    # Priority 3B: Check if any candidate class in _dependency.py has methods in class_method_index
    # matching func_name or callee_name
    for info in valid_candidates:
        c_methods = class_method_index.get(info.class_name.lower()) or class_method_index.get(info.class_name.split(".")[-1].lower())
        if c_methods:
            if func_name in c_methods or (callee_name and callee_name in c_methods):
                return info, info.class_name

    # Priority 3C: Check file stem match
    if file_path:
        file_stem = os.path.splitext(os.path.basename(file_path))[0].lower()
        for info in valid_candidates:
            if file_stem in info.import_line.lower() or file_stem in info.class_name.lower():
                return info, info.class_name

    # Priority 3D: Autogen marked candidates
    for info in valid_candidates:
        if info.is_autogen:
            return info, info.class_name

    # Priority 3E: First valid candidate
    return valid_candidates[0], valid_candidates[0].class_name


def generate_function_call_example(
    call: EndpointCall,
    dependency_ctx: Optional[DependencyContext] = None,
    service_root_path: str = "",
    manual_service_path: str = "",
    known_manual_classes: Optional[Set[str]] = None,
    known_autogen_classes: Optional[Set[str]] = None,
    class_method_index: Optional[Dict[str, Set[str]]] = None
) -> Dict[str, Any]:
    """
    Generate an example of function call strictly using the dependencies
    of the autogenerated microservice (never manual microservice dependencies),
    resolved via reverse engineering from call.function_name.
    """
    func_name = call.function_name
    file_path = call.file_path or "service.py"
    dep_file = dependency_ctx.file_path if dependency_ctx else None

    # Ensure class_method_index is available
    if class_method_index is None:
        class_method_index = build_class_method_index(dir_path=service_root_path, calls=[call])

    chosen_info: Optional[ClassInstantiationInfo] = None
    class_name = call.class_name or "AutogenApiClient"

    if dependency_ctx:
        chosen_info, resolved_class = reverse_engineer_autogen_dependency(
            call=call,
            dependency_ctx=dependency_ctx,
            class_method_index=class_method_index,
            manual_service_path=manual_service_path,
            known_manual_classes=known_manual_classes,
            service_root_path=service_root_path
        )
        if resolved_class:
            class_name = resolved_class

    imports = []
    class_instantiation = ""
    var_name = "client"

    if chosen_info:
        var_name = chosen_info.variable_name or "client"
        class_name = chosen_info.class_name
        if chosen_info.import_line:
            imports.append(chosen_info.import_line)
        class_instantiation = chosen_info.instantiation_code
    else:
        # Fallback to standard autogen module import (NEVER manual)
        mod_name = os.path.splitext(os.path.basename(file_path))[0]
        if service_root_path:
            pkg_name = os.path.basename(os.path.normpath(service_root_path))
            import_str = f"from {pkg_name}.{mod_name} import {class_name}"
        else:
            import_str = f"from {mod_name} import {class_name}"
        imports.append(import_str)
        class_instantiation = f"{var_name} = {class_name}(token=\"YOUR_API_TOKEN\")"

    # Add helper imports/comments if factory function or container exists
    target_class_for_factory = chosen_info.class_name if chosen_info else class_name
    factory_name = None
    if dependency_ctx and target_class_for_factory:
        for c_name, f_call in dependency_ctx.factory_functions.items():
            if c_name.lower() == target_class_for_factory.lower() or c_name.split(".")[-1].lower() == target_class_for_factory.lower():
                if not any(kw in f_call.lower() for kw in ["manual", "legacy", "old"]):
                    factory_name = f_call
                    break

    if factory_name:
        class_instantiation = f"# Option via fabrique autogénérée:\n{var_name} = {factory_name}\n# Ou instanciation directe:\n{class_instantiation}"
    elif chosen_info and chosen_info.enclosing_class:
        enc = chosen_info.enclosing_class
        class_instantiation += f"\n# Ou via conteneur {enc}:\n# deps = {enc}()\n# {var_name} = deps.{chosen_info.variable_name}"

    # Check parameter types and add typing imports if needed
    needed_types = []
    for p in call.function_params:
        ann = p.type_annotation or ""
        for t in ["List", "Dict", "Optional", "Any", "Union", "Tuple"]:
            if t in ann and t not in needed_types:
                needed_types.append(t)
    if needed_types:
        imports.insert(0, f"from typing import {', '.join(needed_types)}")

    # 2. Build Call Parameters Example
    call_args = []
    for p in call.function_params:
        if p.name in ("self", "cls"):
            continue
        val = format_example_value(p)
        call_args.append(f"{p.name}={val}")

    if len(call_args) <= 2 and sum(len(a) for a in call_args) < 50:
        call_str = f"response = {var_name}.{func_name}({', '.join(call_args)})"
    else:
        formatted_args = ",\n    ".join(call_args)
        call_str = f"response = {var_name}.{func_name}(\n    {formatted_args}\n)"

    # 3. Assemble Complete Snippet
    snippet_parts = [
        "# ==================================================",
        f"# Exemple d'appel pour la fonction autogénérée: {func_name}()",
        f"# Endpoint: [{call.http_method}] {call.normalized_endpoint}",
    ]
    if dep_file and chosen_info:
        snippet_parts.append(f"# Dépendance autogénérée issue de: {os.path.basename(dep_file)}")
    snippet_parts.append("# ==================================================\n")

    snippet_parts.append("# 1. Imports nécessaires (microservice autogénéré)")
    snippet_parts.extend(imports)
    snippet_parts.append("\n# 2. Initialisation de la dépendance autogénérée")
    snippet_parts.append(class_instantiation)
    snippet_parts.append("\n# 3. Appel de la fonction du microservice autogénéré")
    snippet_parts.append(call_str)
    snippet_parts.append("print(f\"Résultat reçu: {response}\")")

    full_code = "\n".join(snippet_parts)

    return {
        "function_name": func_name,
        "class_name": class_name,
        "variable_name": var_name,
        "dependency_file": os.path.basename(dep_file) if (dep_file and chosen_info) else None,
        "imports": imports,
        "instantiation": class_instantiation,
        "call_snippet": call_str,
        "full_code": full_code
    }

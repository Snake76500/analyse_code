"""
Parser for autogenerated microservice dependency declaration files (*_dependency.py).
Understands class declarations, imports, and generates realistic code call examples.
"""
import ast
import os
import re
from collections import deque
from dataclasses import dataclass, field
from typing import Dict, List, Optional, Any, Set, Tuple
from .models import EndpointCall, ParameterInfo


@dataclass
class ClassInstantiationInfo:
    class_name: str
    variable_name: str
    import_line: str
    instantiation_code: str
    constructor_kwargs: Dict[str, str] = field(default_factory=dict)
    source_file: str = ""
    enclosing_class: Optional[str] = None
    is_manual: bool = False
    is_autogen: bool = False
    has_sync_api_client: bool = False


def references_sync_api_client(*items: Any) -> bool:
    """
    Check if any text, node or code snippet contains a reference to SyncApiClient.
    Strictly excludes AsyncApiClient / async_api_client occurrences.
    """
    for item in items:
        if not item:
            continue
        s = str(item).lower()
        if re.search(r"(?<!a)sync[_\-]?(api)?[_\-]?(client|sdk)", s):
            return True
        if re.search(r"(?<!a)sync[_\-]?api", s) and "client" in s:
            return True
    return False


@dataclass
class DependencyContext:
    file_path: Optional[str] = None
    file_content: str = ""
    imports: List[str] = field(default_factory=list)
    import_modules: Dict[str, str] = field(default_factory=dict)  # Symbol -> "from module import Symbol"
    instantiations: Dict[str, ClassInstantiationInfo] = field(default_factory=dict)  # ClassName -> info
    instantiations_list: List[ClassInstantiationInfo] = field(default_factory=list)
    factory_functions: Dict[str, str] = field(default_factory=dict)  # ClassName -> "get_client()"
    dependency_classes: List[str] = field(default_factory=list)
    sub_attributes: Dict[str, Dict[str, str]] = field(default_factory=dict)  # parent_class -> {sub_class -> attr_name}


def extract_service_stem_from_dependency_path(file_path: str) -> Optional[str]:
    """
    Extract the homonym target service stem from a dependency file path.
    Example:
      'fichiera_dependency.py' -> 'fichiera'
      'dependency_fichiera.py' -> 'fichiera'
      'fichiera-dependency.py' -> 'fichiera'
      'fichiera_dep.py' -> 'fichiera'
      'controllers/users_dependency.py' -> 'users'
      'dependencies/fichiera.py' -> 'fichiera'
    """
    if not file_path:
        return None
    base = os.path.basename(file_path)
    if not base.endswith(".py"):
        return None
    name = base[:-3]

    # Check folder name (e.g. dependencies/fichiera.py or dependency/users.py)
    norm = os.path.normpath(file_path).replace("\\", "/")
    parts = norm.split("/")
    if len(parts) >= 2 and parts[-2].lower() in ["dependency", "dependencies", "deps"]:
        return name

    # Standard suffixes
    for suffix in [
        "_dependency", "_dependencies", "-dependency", "-dependencies",
        "_dep", "_deps", "-dep", "-deps",
        ".dependency", ".dependencies"
    ]:
        if name.lower().endswith(suffix):
            return name[:-len(suffix)]

    # Standard prefixes
    for prefix in [
        "dependency_", "dependencies_", "dep_", "deps_",
        "dependency-", "dependencies-", "dep-", "deps-"
    ]:
        if name.lower().startswith(prefix):
            return name[len(prefix):]

    # Regex cleanup of dependency keywords anywhere in filename
    cleaned = re.sub(r'(_|-)?dependenc(y|ies)(_|-)?', '', name, flags=re.IGNORECASE)
    cleaned = re.sub(r'(_|-)?deps?(_|-)?', '', cleaned, flags=re.IGNORECASE)
    if cleaned and cleaned.lower() != name.lower():
        return cleaned

    return None


def build_dependency_registry_from_directory(dir_path: str) -> Dict[str, DependencyContext]:
    """
    Discover and parse all *_dependency.py files in a directory.
    Maps homonym_stem (lower-cased) and basenames -> DependencyContext.
    Enforces strict homonym binding: fichiera.py is linked to fichiera_dependency.py.
    """
    registry: Dict[str, DependencyContext] = {}
    if not os.path.exists(dir_path):
        return registry

    def _register(full_p: str, rel_p: str = ""):
        ctx = parse_dependency_file(full_p)
        if not ctx:
            return
        stem = extract_service_stem_from_dependency_path(full_p)
        base = os.path.splitext(os.path.basename(full_p))[0].lower()
        if stem:
            registry[stem.lower()] = ctx
        registry[base] = ctx
        if rel_p:
            rel_stem = extract_service_stem_from_dependency_path(rel_p)
            if rel_stem:
                registry[rel_stem.lower()] = ctx
            rel_base = os.path.splitext(os.path.normpath(rel_p).replace("\\", "/"))[0].lower()
            registry[rel_base] = ctx

    if os.path.isfile(dir_path):
        if "_dependency" in dir_path or "dependency" in dir_path or "_dep" in dir_path:
            _register(dir_path, "")
        return registry

    for root, _, files in os.walk(dir_path):
        if any(skip in root for skip in ["__pycache__", ".venv", "venv", ".git"]):
            continue
        for file in files:
            if file.endswith(".py"):
                f_low = file.lower()
                if "_dependency" in f_low or "dependency" in f_low or "_dep" in f_low or "-dep" in f_low:
                    full_path = os.path.join(root, file)
                    rel_path = os.path.relpath(full_path, dir_path)
                    _register(full_path, rel_path)

    return registry


def build_dependency_registry_from_memory(file_list: List[Dict[str, str]]) -> Dict[str, DependencyContext]:
    """
    Discover and parse all *_dependency.py files in an in-memory virtual file list.
    Maps homonym_stem (lower-cased) and basenames -> DependencyContext.
    """
    registry: Dict[str, DependencyContext] = {}
    for item in file_list:
        path = item.get("path", "")
        content = item.get("content", "")
        if path.endswith(".py") and content:
            f_low = path.lower()
            if "_dependency" in f_low or "dependency" in f_low or "_dep" in f_low or "-dep" in f_low:
                ctx = parse_dependency_content(content, path)
                stem = extract_service_stem_from_dependency_path(path)
                base = os.path.splitext(os.path.basename(path))[0].lower()
                if stem:
                    registry[stem.lower()] = ctx
                registry[base] = ctx
                norm_rel = os.path.splitext(os.path.normpath(path).replace("\\", "/"))[0].lower()
                registry[norm_rel] = ctx
    return registry


def get_homonym_dependency(
    source_file_path: Optional[str],
    registry: Dict[str, DependencyContext]
) -> Optional[DependencyContext]:
    """
    Retrieve the dependency context uniquely linked to its homonym service file.
    Rule: Relie bien les fichiers contenant le même nom.
    e.g. fichiera.py is linked to fichiera_dependency.py.
    """
    if not source_file_path or not registry:
        return None

    # Base stem from the service file: e.g. "fichiera.py" -> "fichiera"
    base_file = os.path.basename(source_file_path)
    stem = os.path.splitext(base_file)[0].lower()
    clean_stem = re.sub(r'(_service|_controller|_api|_client|_router|_view)$', '', stem)

    # 1. Direct stem lookup
    if stem in registry:
        return registry[stem]
    if clean_stem in registry:
        return registry[clean_stem]

    # 2. Check relative path stem if available (e.g. "controllers/fichiera")
    norm_path = os.path.normpath(source_file_path).replace("\\", "/")
    rel_stem = os.path.splitext(norm_path)[0].lower()
    clean_rel = re.sub(r'(_service|_controller|_api|_client|_router|_view)$', '', rel_stem)
    if rel_stem in registry:
        return registry[rel_stem]
    if clean_rel in registry:
        return registry[clean_rel]

    # 3. Match by keys containing stem or stem containing key
    for reg_key, ctx in registry.items():
        reg_k_low = reg_key.lower()
        reg_clean = re.sub(r'(_service|_controller|_api|_client|_router|_view)$', '', reg_k_low)
        if reg_k_low == stem or reg_clean == clean_stem:
            return ctx
        if (len(clean_stem) >= 3 and clean_stem in reg_k_low) or (len(reg_clean) >= 3 and reg_clean in stem):
            return ctx

    # 4. Match by actual dependency file path containing the service stem ("contenant le même nom")
    for reg_key, ctx in registry.items():
        if ctx.file_path:
            dep_base = os.path.basename(ctx.file_path).lower()
            dep_stem = os.path.splitext(dep_base)[0]
            if stem and (stem in dep_stem or (len(clean_stem) >= 3 and clean_stem in dep_stem)):
                return ctx
            dep_extracted = extract_service_stem_from_dependency_path(ctx.file_path)
            if dep_extracted:
                dep_ext_low = dep_extracted.lower()
                if dep_ext_low in stem or (len(clean_stem) >= 3 and dep_ext_low in clean_stem):
                    return ctx

    # 5. Single dependency context in registry fallback
    if len(registry) == 1:
        single_ctx = list(registry.values())[0]
        if single_ctx.file_path:
            dep_base = os.path.basename(single_ctx.file_path).lower()
            if stem in dep_base or clean_stem in dep_base:
                return single_ctx
        return single_ctx

    return None


def find_dependency_file(dir_path: str) -> Optional[str]:
    """Find a Python file containing or ending with '_dependency' in dir_path."""
    if not os.path.exists(dir_path):
        return None

    if os.path.isfile(dir_path):
        if "_dependency" in os.path.basename(dir_path):
            return dir_path
        return None

    for root, _, files in os.walk(dir_path):
        if any(skip in root for skip in ["__pycache__", ".venv", "venv", ".git"]):
            continue
        for file in files:
            if file.endswith(".py") and ("_dependency" in file or file.startswith("dependency")):
                return os.path.join(root, file)

    return None


def find_dependency_in_memory(file_list: List[Dict[str, str]]) -> Optional[Dict[str, str]]:
    """Find a virtual file ending with '_dependency.py' in the in-memory upload list."""
    for item in file_list:
        path = item.get("path", "")
        if path.endswith(".py") and ("_dependency" in path or path.startswith("dependency")):
            return item
    return None


class DependencyFileVisitor(ast.NodeVisitor):
    def __init__(self, file_path: str, source_code: str):
        self.file_path = file_path
        self.source_code = source_code
        self.source_lines = source_code.splitlines()

        self.imports: List[str] = []
        self.import_modules: Dict[str, str] = {}  # Symbol -> import line
        self.instantiations: Dict[str, ClassInstantiationInfo] = {}  # ClassName -> Info
        self.instantiations_list: List[ClassInstantiationInfo] = []
        self.factory_functions: Dict[str, str] = {}
        self.dependency_classes: List[str] = []
        self.sync_classes: Set[str] = set()
        self.sub_attributes: Dict[str, Dict[str, str]] = {}

    def visit_Import(self, node: ast.Import):
        try:
            line = ast.unparse(node)
            self.imports.append(line)
            for alias in node.names:
                name = alias.asname or alias.name
                self.import_modules[name] = line
                if references_sync_api_client(name, alias.name):
                    self.sync_classes.add(name)
        except Exception:
            pass

    def visit_ImportFrom(self, node: ast.ImportFrom):
        try:
            line = ast.unparse(node)
            self.imports.append(line)
            for alias in node.names:
                name = alias.asname or alias.name
                if node.module:
                    self.import_modules[name] = f"from {node.module} import {name}"
                else:
                    self.import_modules[name] = line
                if references_sync_api_client(name, alias.name):
                    self.sync_classes.add(name)
        except Exception:
            pass

    def visit_ClassDef(self, node: ast.ClassDef):
        self.dependency_classes.append(node.name)
        is_sync_class = references_sync_api_client(node.name)
        for base in node.bases:
            try:
                base_str = ast.unparse(base)
                if references_sync_api_client(base_str):
                    is_sync_class = True
            except Exception:
                pass

        if is_sync_class:
            self.sync_classes.add(node.name)

        # Inspect class body for assignments, __init__, and getter methods
        for item in node.body:
            if isinstance(item, ast.FunctionDef) and item.name == "__init__":
                self._inspect_init(node.name, item, is_sync_class=is_sync_class)
            elif isinstance(item, ast.FunctionDef) and item.name != "__init__":
                self._inspect_method(node.name, item)
            elif isinstance(item, ast.AnnAssign):
                type_str = ""
                if item.annotation:
                    try:
                        type_str = ast.unparse(item.annotation)
                    except Exception:
                        pass
                is_sync = is_sync_class or references_sync_api_client(type_str)
                if isinstance(item.value, ast.Call):
                    self._inspect_call_assign(item.target, item.value, enclosing_class=node.name, is_sync_hint=is_sync, type_ann=type_str)
                elif is_sync:
                    self._create_annotated_client(item.target, type_str, enclosing_class=node.name)
            elif isinstance(item, ast.Assign) and isinstance(item.value, ast.Call):
                for target in item.targets:
                    self._inspect_call_assign(target, item.value, enclosing_class=node.name, is_sync_hint=is_sync_class)
        self.generic_visit(node)

    def visit_FunctionDef(self, node: ast.FunctionDef):
        return_type = None
        if node.returns:
            try:
                return_type = ast.unparse(node.returns)
            except Exception:
                pass

        is_sync_func = references_sync_api_client(node.name, return_type)

        for stmt in node.body:
            if isinstance(stmt, ast.Return):
                if isinstance(stmt.value, ast.Call):
                    func_name = self._get_call_name(stmt.value)
                    target_class = return_type or func_name
                    if references_sync_api_client(func_name, return_type):
                        is_sync_func = True
                    if target_class:
                        self.factory_functions[target_class] = f"{node.name}()"
                        self._inspect_call_assign(
                            ast.Name(id="sync_api_client" if is_sync_func else "client", ctx=ast.Store()),
                            stmt.value,
                            is_sync_hint=is_sync_func
                        )
                elif is_sync_func and return_type:
                    self.factory_functions[return_type] = f"{node.name}()"
                    import_line = self.import_modules.get(return_type, "")
                    info = ClassInstantiationInfo(
                        class_name=return_type,
                        variable_name="sync_api_client",
                        import_line=import_line,
                        instantiation_code=f"sync_api_client = {node.name}()",
                        source_file=self.file_path,
                        has_sync_api_client=True,
                        is_autogen=True
                    )
                    self.instantiations[return_type] = info
                    self.instantiations_list.append(info)

        self.generic_visit(node)

    def visit_Assign(self, node: ast.Assign):
        if isinstance(node.value, ast.Call):
            for target in node.targets:
                self._inspect_call_assign(target, node.value)
        self.generic_visit(node)

    def visit_AnnAssign(self, node: ast.AnnAssign):
        type_str = ""
        if node.annotation:
            try:
                type_str = ast.unparse(node.annotation)
            except Exception:
                pass
        is_sync = references_sync_api_client(type_str)
        if isinstance(node.value, ast.Call):
            self._inspect_call_assign(node.target, node.value, is_sync_hint=is_sync, type_ann=type_str)
        elif is_sync:
            self._create_annotated_client(node.target, type_str)
        self.generic_visit(node)

    def _create_annotated_client(self, target_node: ast.AST, type_str: str, enclosing_class: str = ""):
        var_name = "sync_api_client"
        try:
            target_str = ast.unparse(target_node)
            if target_str.startswith("self."):
                var_name = target_str.replace("self.", "")
            else:
                var_name = target_str
        except Exception:
            pass
        cls_name = type_str if type_str else "SyncApiClient"
        import_line = self.import_modules.get(cls_name) or self.import_modules.get("SyncApiClient", "")
        info = ClassInstantiationInfo(
            class_name=cls_name,
            variable_name=var_name,
            import_line=import_line,
            instantiation_code=f"{var_name} = {cls_name}()",
            source_file=self.file_path,
            enclosing_class=enclosing_class,
            has_sync_api_client=True,
            is_autogen=True
        )
        self.instantiations[cls_name] = info
        self.instantiations_list.append(info)

    def _inspect_init(self, enclosing_class: str, init_node: ast.FunctionDef, is_sync_class: bool = False):
        for stmt in init_node.body:
            if isinstance(stmt, ast.Assign) and isinstance(stmt.value, ast.Call):
                for target in stmt.targets:
                    self._inspect_call_assign(target, stmt.value, enclosing_class=enclosing_class, is_sync_hint=is_sync_class)
            elif isinstance(stmt, ast.AnnAssign):
                type_str = ""
                if stmt.annotation:
                    try:
                        type_str = ast.unparse(stmt.annotation)
                    except Exception:
                        pass
                is_sync = is_sync_class or references_sync_api_client(type_str)
                if isinstance(stmt.value, ast.Call):
                    self._inspect_call_assign(stmt.target, stmt.value, enclosing_class=enclosing_class, is_sync_hint=is_sync, type_ann=type_str)
                elif is_sync:
                    self._create_annotated_client(stmt.target, type_str, enclosing_class=enclosing_class)

    def _inspect_method(self, enclosing_class: str, func_node: ast.FunctionDef):
        return_type = None
        if func_node.returns:
            try:
                return_type = ast.unparse(func_node.returns)
            except Exception:
                pass

        for stmt in func_node.body:
            if isinstance(stmt, ast.Return):
                if isinstance(stmt.value, ast.Call):
                    func_name = self._get_call_name(stmt.value)
                    target_class = return_type or func_name
                    if target_class:
                        self.factory_functions[target_class] = f"{enclosing_class}().{func_node.name}()"
                elif isinstance(stmt.value, ast.Attribute) and return_type:
                    self.factory_functions[return_type] = f"{enclosing_class}().{func_node.name}()"

    def _get_call_name(self, call_node: ast.Call) -> str:
        try:
            return ast.unparse(call_node.func)
        except Exception:
            return ""

    def _inspect_call_assign(self, target_node: ast.AST, call_node: ast.Call, enclosing_class: str = "", is_sync_hint: bool = False, type_ann: str = ""):
        class_name = self._get_call_name(call_node)
        # Handle self.client or client
        var_name = "client"
        try:
            target_str = ast.unparse(target_node)
            if target_str.startswith("self."):
                var_name = target_str.replace("self.", "")
            else:
                var_name = target_str
        except Exception:
            pass

        kwargs = {}
        for kw in call_node.keywords:
            if kw.arg:
                try:
                    kwargs[kw.arg] = ast.unparse(kw.value)
                except Exception:
                    kwargs[kw.arg] = "..."

        call_args_str = ""
        try:
            call_args_str = " ".join([ast.unparse(a) for a in call_node.args])
        except Exception:
            pass

        try:
            call_code = ast.unparse(call_node)
        except Exception:
            args_str = ", ".join([f"{k}={v}" for k, v in kwargs.items()])
            call_code = f"{class_name}({args_str})"

        import_line = self.import_modules.get(class_name, "")
        if not import_line:
            # Fallback if class is imported
            for sym, imp in self.import_modules.items():
                if sym == class_name or sym == class_name.split(".")[-1]:
                    import_line = imp
                    break

        lower_check = f"{class_name} {var_name} {import_line} {enclosing_class}".lower()
        is_manual = any(kw in lower_check for kw in ["manual", "legacy", "old", "v1", "ancient", "deprecated"])

        # Check references to SyncApiClient
        kwargs_combined = " ".join(f"{k} {v}" for k, v in kwargs.items())
        has_sync_api_client = (
            is_sync_hint or
            class_name in self.sync_classes or
            references_sync_api_client(
                class_name, var_name, call_code,
                enclosing_class, type_ann, kwargs_combined, call_args_str
            )
        )

        is_autogen = has_sync_api_client or any(kw in lower_check for kw in ["autogen", "auto", "openapi", "swagger", "generated"])

        info = ClassInstantiationInfo(
            class_name=class_name,
            variable_name=var_name,
            import_line=import_line,
            instantiation_code=f"{var_name} = {call_code}",
            constructor_kwargs=kwargs,
            source_file=self.file_path,
            enclosing_class=enclosing_class,
            is_manual=is_manual,
            is_autogen=is_autogen,
            has_sync_api_client=has_sync_api_client
        )
        self.instantiations[class_name] = info
        self.instantiations_list.append(info)

        if enclosing_class:
            enc_low = enclosing_class.lower()
            if enc_low not in self.sub_attributes:
                self.sub_attributes[enc_low] = {}
            self.sub_attributes[enc_low][class_name.lower()] = var_name
            self.sub_attributes[enc_low][class_name.split(".")[-1].lower()] = var_name


def parse_dependency_content(content: str, file_path: str = "dependency.py") -> DependencyContext:
    """Parse the AST of a dependency declaration file."""
    ctx = DependencyContext(file_path=file_path, file_content=content)
    try:
        tree = ast.parse(content, filename=file_path)
        visitor = DependencyFileVisitor(file_path, content)
        visitor.visit(tree)

        # Safety check: if file references SyncApiClient but no instantiation was tagged, synthesize one
        has_any_sync = any(info.has_sync_api_client for info in visitor.instantiations_list)
        if not has_any_sync and references_sync_api_client(content):
            imp = ""
            for sym, line in visitor.import_modules.items():
                if references_sync_api_client(sym, line):
                    imp = line
                    break
            if not imp:
                for line in content.splitlines():
                    if references_sync_api_client(line) and "import" in line:
                        imp = line.strip()
                        break

            synth_info = ClassInstantiationInfo(
                class_name="SyncApiClient",
                variable_name="sync_api_client",
                import_line=imp,
                instantiation_code="sync_api_client = SyncApiClient()",
                source_file=file_path,
                is_manual=False,
                is_autogen=True,
                has_sync_api_client=True
            )
            visitor.instantiations["SyncApiClient"] = synth_info
            visitor.instantiations_list.append(synth_info)

        ctx.imports = visitor.imports
        ctx.import_modules = visitor.import_modules
        ctx.instantiations = visitor.instantiations
        ctx.instantiations_list = visitor.instantiations_list
        ctx.factory_functions = visitor.factory_functions
        ctx.dependency_classes = visitor.dependency_classes
        ctx.sub_attributes = visitor.sub_attributes
    except Exception as e:
        print(f"Warning: could not parse dependency file {file_path}: {e}")

    return ctx


def parse_dependency_file(file_path: str) -> Optional[DependencyContext]:
    """Parse a dependency file from disk."""
    if not os.path.exists(file_path):
        return None
    try:
        with open(file_path, "r", encoding="utf-8", errors="replace") as f:
            content = f.read()
        return parse_dependency_content(content, file_path)
    except Exception as e:
        print(f"Warning: could not read {file_path}: {e}")
        return None


def format_example_value(param: ParameterInfo) -> str:
    """Generate a realistic, syntactically valid Python value for a parameter."""
    name = param.name.lower()
    type_ann = (param.type_annotation or "").lower()

    # Name-based heuristic overrides
    if name in {"id", "user_id", "customer_id", "item_id", "order_id"}:
        if "str" in type_ann:
            return '"usr_101"'
        return "101"
    if name in {"token", "api_key", "key", "auth", "secret"}:
        return '"your_api_token_here"'
    if name in {"voucher", "promo_code", "discount_code", "coupon"}:
        return '"SPRING10"'
    if name in {"q", "query", "search", "keyword"}:
        return '"winter jackets"'
    if name in {"limit", "page_size", "count", "max_results"}:
        return "25"
    if name in {"offset", "skip", "page"}:
        return "0"
    if name in {"quantity", "qty", "stock"}:
        return "100"
    if name in {"currency"}:
        return '"EUR"'
    if name in {"date", "start_date", "end_date", "timestamp"}:
        return '"2026-10-15"'
    if name in {"email"}:
        return '"user@example.com"'
    if name in {"view_id"}:
        return '"overview"'
    if name in {"product_id"}:
        return "55"
    if name in {"purge_data", "include_billing", "is_active", "expand", "force"}:
        return "True"
    if name in {"items", "cart", "products"}:
        return '[{"item_id": 1, "qty": 2}]'
    if name in {"payload", "data", "body"}:
        return '{"name": "Sample Order", "status": "pending"}'

    # Type-based heuristic
    if "int" in type_ann:
        return param.default_value if param.default_value and param.default_value != "None" else "42"
    if "float" in type_ann:
        return param.default_value if param.default_value and param.default_value != "None" else "19.99"
    if "bool" in type_ann:
        return param.default_value if param.default_value and param.default_value != "None" else "True"
    if "list" in type_ann:
        if param.default_value and param.default_value not in ("None", "[]"):
            return param.default_value
        return '["item_1", "item_2"]'
    if "dict" in type_ann:
        if param.default_value and param.default_value not in ("None", "{}"):
            return param.default_value
        return '{"key": "value"}'
    if "str" in type_ann:
        if param.default_value and param.default_value != "None":
            return param.default_value
        return f'"{name}_val"'

    # Default value fallback
    if param.default_value and param.default_value != "None":
        return param.default_value

    return f'"{name}_sample"'


def is_manual_dependency(info: ClassInstantiationInfo, manual_service_path: str = "") -> bool:
    """
    Check if a dependency instantiation belongs to the manual microservice.
    """
    if info.is_manual:
        return True

    lower_class = info.class_name.lower()
    lower_var = info.variable_name.lower()
    lower_import = (info.import_line or "").lower()

    for kw in ["manual", "legacy", "old", "v1", "ancient", "deprecated"]:
        if kw in lower_class or kw in lower_var or kw in lower_import:
            return True

    if manual_service_path:
        base_manual = os.path.basename(os.path.normpath(manual_service_path)).lower()
        if base_manual and base_manual in lower_import:
            return True

    return False


def is_autogen_dependency(
    info: ClassInstantiationInfo,
    target_class_name: Optional[str] = None,
    target_function_name: Optional[str] = None,
    service_file_stem: Optional[str] = None,
    autogen_service_path: str = ""
) -> bool:
    """
    Check if a dependency instantiation belongs to the autogenerated microservice.
    """
    if is_manual_dependency(info, ""):
        return False

    if info.is_autogen:
        return True

    lower_class = info.class_name.lower()
    lower_var = info.variable_name.lower()
    lower_import = (info.import_line or "").lower()

    if target_class_name:
        target_lower = target_class_name.lower()
        if lower_class == target_lower or lower_class.split(".")[-1] == target_lower:
            return True

    for kw in ["autogen", "auto", "openapi", "swagger", "generated"]:
        if kw in lower_class or kw in lower_var or kw in lower_import:
            return True

    if service_file_stem and service_file_stem.lower() in lower_import:
        return True

    if autogen_service_path:
        base_autogen = os.path.basename(os.path.normpath(autogen_service_path)).lower()
        if base_autogen and base_autogen in lower_import:
            return True

    return False


def build_class_method_index(
    dir_path: str = "",
    file_list: Optional[List[Dict[str, str]]] = None,
    calls: Optional[List[EndpointCall]] = None
) -> Dict[str, Set[str]]:
    """
    Build a comprehensive index of class_name (lowercased and original) -> set of methods
    defined in that class across all autogenerated microservice files.
    """
    index: Dict[str, Set[str]] = {}

    def _add_method(cls_name: str, m_name: str):
        if not cls_name or not m_name:
            return
        cls_low = cls_name.lower()
        if cls_low not in index:
            index[cls_low] = set()
        index[cls_low].add(m_name)
        if cls_name not in index:
            index[cls_name] = set()
        index[cls_name].add(m_name)
        base = cls_name.split(".")[-1]
        base_low = base.lower()
        if base_low not in index:
            index[base_low] = set()
        index[base_low].add(m_name)

    # 1. Index from existing parsed EndpointCalls
    if calls:
        for c in calls:
            if c.class_name and c.function_name:
                _add_method(c.class_name, c.function_name)
            if c.class_name and c.callee_function:
                _add_method(c.class_name, c.callee_function)

    # 2. Index from virtual file list
    def _parse_and_index_code(code: str, fname: str = ""):
        try:
            tree = ast.parse(code, filename=fname)
            for node in ast.walk(tree):
                if isinstance(node, ast.ClassDef):
                    for item in node.body:
                        if isinstance(item, (ast.FunctionDef, ast.AsyncFunctionDef)):
                            _add_method(node.name, item.name)
        except Exception:
            pass

    if file_list:
        for item in file_list:
            path = item.get("path", "")
            content = item.get("content", "")
            if path.endswith(".py") and content and not path.endswith("_dependency.py") and not path.endswith("_dependencies.py"):
                _parse_and_index_code(content, path)

    # 3. Index from directory path
    if dir_path and os.path.exists(dir_path):
        if os.path.isfile(dir_path):
            if not dir_path.endswith("_dependency.py") and not dir_path.endswith("_dependencies.py"):
                try:
                    with open(dir_path, "r", encoding="utf-8", errors="replace") as f:
                        _parse_and_index_code(f.read(), dir_path)
                except Exception:
                    pass
        else:
            for root, _, files in os.walk(dir_path):
                if any(skip in root for skip in ["__pycache__", ".venv", "venv", ".git"]):
                    continue
                for file in files:
                    if file.endswith(".py") and not file.endswith("_dependency.py") and not file.endswith("_dependencies.py"):
                        full_path = os.path.join(root, file)
                        try:
                            with open(full_path, "r", encoding="utf-8", errors="replace") as f:
                                _parse_and_index_code(f.read(), full_path)
                        except Exception:
                            pass

    return index


class ClassHierarchyVisitor(ast.NodeVisitor):
    """
    AST Visitor extracting class hierarchy, member attributes instantiating sub-classes,
    properties, and method names to resolve precise call paths like client.views.function_name.
    """
    def __init__(self, file_path: str = ""):
        self.file_path = file_path
        # parent_class_lower -> { sub_class_lower: attribute_name }
        self.sub_attributes: Dict[str, Dict[str, str]] = {}
        # class_lower -> list of base class names (lowered)
        self.class_bases: Dict[str, List[str]] = {}
        # class_lower -> set of method names
        self.class_methods: Dict[str, Set[str]] = {}

    def visit_ClassDef(self, node: ast.ClassDef):
        cls_name = node.name
        cls_low = cls_name.lower()
        if cls_low not in self.sub_attributes:
            self.sub_attributes[cls_low] = {}
        if cls_low not in self.class_methods:
            self.class_methods[cls_low] = set()

        bases = []
        for base in node.bases:
            try:
                base_name = ast.unparse(base).split(".")[-1].lower()
                bases.append(base_name)
            except Exception:
                pass
        self.class_bases[cls_low] = bases

        # Inspect class-level statements
        for item in node.body:
            if isinstance(item, (ast.FunctionDef, ast.AsyncFunctionDef)):
                self.class_methods[cls_low].add(item.name)
                # Check for @property
                is_prop = any(
                    (isinstance(d, ast.Name) and d.id == "property") or
                    (isinstance(d, ast.Attribute) and d.attr == "property")
                    for d in item.decorator_list
                )
                if is_prop:
                    ret_type = ""
                    if item.returns:
                        try:
                            ret_type = ast.unparse(item.returns).split(".")[-1]
                        except Exception:
                            pass
                    if not ret_type:
                        for s in item.body:
                            if isinstance(s, ast.Return) and isinstance(s.value, ast.Call):
                                try:
                                    ret_type = ast.unparse(s.value.func).split(".")[-1]
                                    break
                                except Exception:
                                    pass
                    if ret_type:
                        self._register_sub_attribute(cls_name, ret_type, item.name)

                # Inspect statements in method body (e.g. __init__ or setup methods)
                for stmt in item.body:
                    self._inspect_statement(cls_name, stmt)

            elif isinstance(item, ast.AnnAssign):
                target_name = ""
                if isinstance(item.target, ast.Name):
                    target_name = item.target.id
                type_cls = ""
                if item.annotation:
                    try:
                        type_cls = ast.unparse(item.annotation).split(".")[-1]
                    except Exception:
                        pass
                if target_name and type_cls:
                    self._register_sub_attribute(cls_name, type_cls, target_name)

            elif isinstance(item, ast.Assign) and isinstance(item.value, ast.Call):
                for target in item.targets:
                    if isinstance(target, ast.Name):
                        try:
                            func_name = ast.unparse(item.value.func).split(".")[-1]
                            self._register_sub_attribute(cls_name, func_name, target.id)
                        except Exception:
                            pass

        self.generic_visit(node)

    def _inspect_statement(self, cls_name: str, stmt: ast.AST):
        # self.<attr> = SubClass(...)
        if isinstance(stmt, ast.Assign) and isinstance(stmt.value, ast.Call):
            call_cls = ""
            try:
                call_cls = ast.unparse(stmt.value.func).split(".")[-1]
            except Exception:
                pass
            if call_cls:
                for target in stmt.targets:
                    attr_name = self._extract_attr_name(target, allow_bare_name=False)
                    if attr_name:
                        self._register_sub_attribute(cls_name, call_cls, attr_name)

        # self.<attr>: SubClass = ... or self.<attr>: SubClass
        elif isinstance(stmt, ast.AnnAssign):
            attr_name = self._extract_attr_name(stmt.target, allow_bare_name=False)
            type_cls = ""
            if stmt.annotation:
                try:
                    type_cls = ast.unparse(stmt.annotation).split(".")[-1]
                except Exception:
                    pass
            if not type_cls and isinstance(stmt.value, ast.Call):
                try:
                    type_cls = ast.unparse(stmt.value.func).split(".")[-1]
                except Exception:
                    pass
            if attr_name and type_cls:
                self._register_sub_attribute(cls_name, type_cls, attr_name)

    def _extract_attr_name(self, target_node: ast.AST, allow_bare_name: bool = False) -> Optional[str]:
        if isinstance(target_node, ast.Attribute):
            if isinstance(target_node.value, ast.Name) and target_node.value.id == "self":
                if not target_node.attr.startswith("_"):
                    return target_node.attr
            try:
                t_str = ast.unparse(target_node)
                if t_str.startswith("self.") and not t_str.startswith("self._"):
                    return t_str[5:]
            except Exception:
                pass
        elif allow_bare_name and isinstance(target_node, ast.Name):
            if not target_node.id.startswith("_"):
                return target_node.id
        return None

    def _register_sub_attribute(self, parent_cls: str, child_cls: str, attr_name: str):
        if not parent_cls or not child_cls or not attr_name:
            return
        p_low = parent_cls.lower()
        if p_low not in self.sub_attributes:
            self.sub_attributes[p_low] = {}

        c_low = child_cls.lower()
        self.sub_attributes[p_low][c_low] = attr_name

        # Register normalized variants (e.g. SynViewsApi <-> SyncViewsApi <-> ViewsApi)
        variants = {c_low}
        if c_low.startswith("syn") and not c_low.startswith("sync"):
            variants.add("sync" + c_low[3:])
        elif c_low.startswith("sync"):
            variants.add("syn" + c_low[4:])

        stripped = re.sub(r'^(sync|syn|async)', '', c_low)
        stripped = re.sub(r'(api|client|service|controller)$', '', stripped)
        if stripped:
            variants.add(stripped)
            variants.add(stripped + "api")
            variants.add("sync" + stripped + "api")
            variants.add("syn" + stripped + "api")

        for v in variants:
            if v not in self.sub_attributes[p_low]:
                self.sub_attributes[p_low][v] = attr_name

    def finalize_inheritance(self):
        """Propagate inherited sub-attributes from base classes down to subclasses."""
        changed = True
        iterations = 0
        while changed and iterations < 10:
            changed = False
            iterations += 1
            for cls_low, bases in self.class_bases.items():
                for base_low in bases:
                    if base_low in self.sub_attributes:
                        for child_key, attr_val in self.sub_attributes[base_low].items():
                            if child_key not in self.sub_attributes[cls_low]:
                                self.sub_attributes[cls_low][child_key] = attr_val
                                changed = True
                    if base_low in self.class_methods:
                        for m in self.class_methods[base_low]:
                            if m not in self.class_methods[cls_low]:
                                self.class_methods[cls_low].add(m)
                                changed = True


def build_class_subattributes_index(
    dir_path: str = "",
    file_list: Optional[List[Dict[str, str]]] = None,
    dependency_registry: Optional[Dict[str, DependencyContext]] = None
) -> Dict[str, Dict[str, str]]:
    """
    Scan all autogenerated microservice files and dependency declaration files
    to build an index of parent_class_name.lower() -> { sub_class_name.lower(): attribute_name }.
    Enables precise path resolution such as:
    SyncApiClient -> SynViewsApi -> self.views = SynViewsApi(self) -> path: "views"
    """
    visitor = ClassHierarchyVisitor()

    def _parse_code(code: str, fname: str = ""):
        try:
            tree = ast.parse(code, filename=fname)
            visitor.visit(tree)
        except Exception:
            pass

    # 1. From virtual file list
    if file_list:
        for item in file_list:
            path = item.get("path", "")
            content = item.get("content", "")
            if path.endswith(".py") and content:
                _parse_code(content, path)

    # 2. From disk directory
    if dir_path and os.path.exists(dir_path):
        if os.path.isfile(dir_path):
            try:
                with open(dir_path, "r", encoding="utf-8", errors="replace") as f:
                    _parse_code(f.read(), dir_path)
            except Exception:
                pass
        else:
            for root, _, files in os.walk(dir_path):
                if any(skip in root for skip in ["__pycache__", ".venv", "venv", ".git"]):
                    continue
                for file in files:
                    if file.endswith(".py"):
                        full_p = os.path.join(root, file)
                        try:
                            with open(full_p, "r", encoding="utf-8", errors="replace") as f:
                                _parse_code(f.read(), full_p)
                        except Exception:
                            pass

    # 3. From dependency_registry
    if dependency_registry:
        for ctx in dependency_registry.values():
            if ctx.file_content:
                _parse_code(ctx.file_content, ctx.file_path or "dependency.py")
            if ctx.sub_attributes:
                for p_cls, sub_map in ctx.sub_attributes.items():
                    if p_cls not in visitor.sub_attributes:
                        visitor.sub_attributes[p_cls] = {}
                    visitor.sub_attributes[p_cls].update(sub_map)

    visitor.finalize_inheritance()
    return visitor.sub_attributes


def get_sync_api_client_variable_map(
    dir_path: str = "",
    file_list: Optional[List[Dict[str, str]]] = None,
    dependency_registry: Optional[Dict[str, DependencyContext]] = None
) -> Dict[str, str]:
    """
    Search for class SyncApiClient across all autogenerated microservice files
    and dependency files.
    Extract the member variable names that instantiate other classes:
      self.<var_name> = <ClassName>(...)
      self.<var_name>: <ClassName> = ...
      @property def <var_name>(self) -> <ClassName>:
    Returns mapping: { <ClassName>: <var_name>, <ClassName.lower()>: <var_name>, ... }
    """
    class_to_var: Dict[str, str] = {}

    def _register(cls_name: str, var_name: str):
        if not cls_name or not var_name:
            return
        clean_var = var_name.lstrip("_") if var_name.startswith("_") else var_name
        if not clean_var:
            clean_var = var_name
        cls_base = cls_name.split(".")[-1]
        cls_low = cls_base.lower()

        class_to_var[cls_base] = clean_var
        class_to_var[cls_low] = clean_var

        # Register normalized variants (syn <-> sync, views, etc.)
        if cls_low.startswith("syn") and not cls_low.startswith("sync"):
            class_to_var["sync" + cls_low[3:]] = clean_var
        elif cls_low.startswith("sync"):
            class_to_var["syn" + cls_low[4:]] = clean_var

        stem = re.sub(r'^(sync|syn|async)', '', cls_low)
        stem = re.sub(r'(api|client|service|controller)$', '', stem)
        if stem:
            class_to_var[stem] = clean_var
            class_to_var[stem + "api"] = clean_var
            class_to_var["sync" + stem + "api"] = clean_var
            class_to_var["syn" + stem + "api"] = clean_var

    def _inspect_sync_client_class(cls_node: ast.ClassDef):
        # 1. Properties
        for item in cls_node.body:
            if isinstance(item, (ast.FunctionDef, ast.AsyncFunctionDef)):
                is_prop = any(
                    (isinstance(d, ast.Name) and d.id == "property") or
                    (isinstance(d, ast.Attribute) and d.attr == "property")
                    for d in item.decorator_list
                )
                if is_prop:
                    ret_cls = ""
                    if item.returns:
                        try:
                            ret_cls = ast.unparse(item.returns).split(".")[-1]
                        except Exception:
                            pass
                    if not ret_cls:
                        for s in item.body:
                            if isinstance(s, ast.Return) and isinstance(s.value, ast.Call):
                                try:
                                    ret_cls = ast.unparse(s.value.func).split(".")[-1]
                                    break
                                except Exception:
                                    pass
                    if ret_cls:
                        _register(ret_cls, item.name)

        # 2. Methods body (e.g. __init__ or setup methods)
        for item in cls_node.body:
            if isinstance(item, (ast.FunctionDef, ast.AsyncFunctionDef)):
                for stmt in ast.walk(item):
                    if isinstance(stmt, ast.Assign) and isinstance(stmt.value, ast.Call):
                        call_cls = ""
                        try:
                            call_cls = ast.unparse(stmt.value.func).split(".")[-1]
                        except Exception:
                            pass
                        if call_cls:
                            for target in stmt.targets:
                                if isinstance(target, ast.Attribute) and isinstance(target.value, ast.Name) and target.value.id == "self":
                                    _register(call_cls, target.attr)
                    elif isinstance(stmt, ast.AnnAssign):
                        target_name = ""
                        if isinstance(stmt.target, ast.Attribute) and isinstance(stmt.target.value, ast.Name) and stmt.target.value.id == "self":
                            target_name = stmt.target.attr
                        type_cls = ""
                        if stmt.annotation:
                            try:
                                type_cls = ast.unparse(stmt.annotation).split(".")[-1]
                            except Exception:
                                pass
                        if not type_cls and isinstance(stmt.value, ast.Call):
                            try:
                                type_cls = ast.unparse(stmt.value.func).split(".")[-1]
                            except Exception:
                                pass
                        if target_name and type_cls:
                            _register(type_cls, target_name)

            elif isinstance(item, ast.AnnAssign):
                target_name = item.target.id if isinstance(item.target, ast.Name) else ""
                type_cls = ""
                if item.annotation:
                    try:
                        type_cls = ast.unparse(item.annotation).split(".")[-1]
                    except Exception:
                        pass
                if target_name and type_cls:
                    _register(type_cls, target_name)

            elif isinstance(item, ast.Assign) and isinstance(item.value, ast.Call):
                call_cls = ""
                try:
                    call_cls = ast.unparse(item.value.func).split(".")[-1]
                except Exception:
                    pass
                if call_cls:
                    for target in item.targets:
                        if isinstance(target, ast.Name):
                            _register(call_cls, target.id)

    def _parse_code_for_sync_client(code: str, fname: str = ""):
        try:
            tree = ast.parse(code, filename=fname)
            for node in ast.walk(tree):
                if isinstance(node, ast.ClassDef):
                    if node.name == "SyncApiClient" or node.name.lower() == "syncapiclient" or references_sync_api_client(node.name):
                        _inspect_sync_client_class(node)
        except Exception:
            pass

    if file_list:
        for item in file_list:
            content = item.get("content", "")
            path = item.get("path", "")
            if content and path.endswith(".py"):
                _parse_code_for_sync_client(content, path)

    if dependency_registry:
        for ctx in dependency_registry.values():
            if ctx.file_content:
                _parse_code_for_sync_client(ctx.file_content, ctx.file_path or "dependency.py")

    if dir_path and os.path.exists(dir_path):
        if os.path.isfile(dir_path):
            try:
                with open(dir_path, "r", encoding="utf-8", errors="replace") as f:
                    _parse_code_for_sync_client(f.read(), dir_path)
            except Exception:
                pass
        else:
            for root, _, files in os.walk(dir_path):
                if any(skip in root for skip in ["__pycache__", ".venv", "venv", ".git"]):
                    continue
                for file in files:
                    if file.endswith(".py"):
                        full_p = os.path.join(root, file)
                        try:
                            with open(full_p, "r", encoding="utf-8", errors="replace") as f:
                                _parse_code_for_sync_client(f.read(), full_p)
                        except Exception:
                            pass

    return class_to_var


def resolve_function_call_path(
    root_class: str,
    func_name: str,
    callee_name: Optional[str] = None,
    target_class: Optional[str] = None,
    class_method_index: Optional[Dict[str, Set[str]]] = None,
    class_subattributes_index: Optional[Dict[str, Dict[str, str]]] = None
) -> Tuple[str, str]:
    """
    Resolve the exact attribute call path from the root instantiated client
    to the implementing sub-class defining func_name.
    
    Example:
      root_class: "SyncApiClient"
      func_name: "get_product_views"
      SyncApiClient has self.views = SynViewsApi(self)
      SynViewsApi defines get_product_views
      -> returns ("views", "SynViewsApi")
      Resulting call: response = client.views.get_product_views(...)
    """
    if not root_class:
        return "", root_class

    c_methods = class_method_index or {}
    c_subattrs = class_subattributes_index or {}

    root_low = root_class.lower()
    root_base_low = root_class.split(".")[-1].lower()

    # Find all classes that implement func_name or callee_name
    classes_with_method: Set[str] = set()
    for cls_name, methods in c_methods.items():
        if func_name in methods or (callee_name and callee_name in methods):
            classes_with_method.add(cls_name.lower())
            classes_with_method.add(cls_name.split(".")[-1].lower())

    if target_class:
        classes_with_method.add(target_class.lower())
        classes_with_method.add(target_class.split(".")[-1].lower())

    # If classes_with_method is empty, check if func_name contains clue
    # e.g. get_product_views -> "views"
    inferred_sub_stem = None
    m_stem = re.search(r'(views?|users?|orders?|items?|products?|inventory|auth|payments?|audit)', func_name, re.I)
    if m_stem:
        inferred_sub_stem = m_stem.group(1).lower()

    # Priority 1: Check BFS in class_subattributes_index starting from root_class
    start_nodes = [root_low]
    if root_base_low != root_low:
        start_nodes.append(root_base_low)

    for start_node in start_nodes:
        if start_node not in c_subattrs and not any(start_node in k for k in c_subattrs):
            continue

        queue = deque([(start_node, [])])
        visited = {start_node}

        while queue:
            curr_cls, path = queue.popleft()

            # If current node is a sub-step and implements the target method
            if path and (curr_cls in classes_with_method or (target_class and curr_cls == target_class.lower())):
                return ".".join(path), curr_cls

            sub_map = c_subattrs.get(curr_cls, {})
            for sub_cls, attr_name in sub_map.items():
                sub_low = sub_cls.lower()
                if sub_low in classes_with_method or (target_class and sub_low == target_class.lower()):
                    return ".".join(path + [attr_name]), sub_cls
                if sub_low not in visited:
                    visited.add(sub_low)
                    queue.append((sub_low, path + [attr_name]))

    # Priority 2: Check if func_name is directly on root_class or its base classes
    root_methods = c_methods.get(root_low) or c_methods.get(root_base_low) or set()
    if func_name in root_methods or (callee_name and callee_name in root_methods):
        return "", root_class

    # Priority 3: Inferred sub-attribute from inferred_sub_stem
    if inferred_sub_stem:
        for start_node in start_nodes:
            sub_map = c_subattrs.get(start_node, {})
            for sub_cls, attr_name in sub_map.items():
                if inferred_sub_stem in attr_name.lower() or inferred_sub_stem in sub_cls.lower():
                    return attr_name, sub_cls

    # Priority 4: If target_class is a sub-class like SynViewsApi / SyncViewsApi,
    # infer attribute name directly by cleaning the name ONLY IF root has this attribute
    if target_class and target_class.lower() != root_low and target_class.lower() != root_base_low:
        t_clean = re.sub(r'^(sync|syn|async)', '', target_class, flags=re.I)
        t_clean = re.sub(r'(api|client|service|controller)$', '', t_clean, flags=re.I).lower()
        if t_clean:
            for start_node in start_nodes:
                sub_map = c_subattrs.get(start_node, {})
                for sub_cls, attr_name in sub_map.items():
                    if attr_name.lower() == t_clean or t_clean in attr_name.lower():
                        return attr_name, target_class

    return "", root_class


def reverse_engineer_autogen_dependency(
    call: EndpointCall,
    dependency_ctx: DependencyContext,
    class_method_index: Dict[str, Set[str]],
    manual_service_path: str = "",
    known_manual_classes: Optional[Set[str]] = None,
    service_root_path: str = "",
    class_subattributes_index: Optional[Dict[str, Dict[str, str]]] = None
) -> Tuple[Optional[ClassInstantiationInfo], str]:
    """
    Reverse engineering to find the exact dependency linked to the autogenerated function:
    1. Identify all candidate source classes in the autogenerated microservice that define or implement call.function_name.
    2. Check which candidate in _dependency.py provides/instantiates that specific class or provides sub-attributes linking to it.
    3. Verify method existence on candidates.
    4. Reject any dependency associated with the manual microservice.
    """
    known_manual = set(known_manual_classes or [])

    # Filter out all manual dependencies from dependency_ctx
    raw_candidates = dependency_ctx.instantiations_list or list(dependency_ctx.instantiations.values())
    valid_candidates: List[ClassInstantiationInfo] = []
    for info in raw_candidates:
        if info.class_name in known_manual or is_manual_dependency(info, manual_service_path):
            continue
        valid_candidates.append(info)

    # Rule 1: Prioritize dependencies containing a reference to SyncApiClient
    sync_candidates = [c for c in valid_candidates if getattr(c, "has_sync_api_client", False)]
    if not sync_candidates and references_sync_api_client(dependency_ctx.file_content):
        # Synthesize SyncApiClient candidate if mentioned anywhere in the dependency file
        imp = dependency_ctx.import_modules.get("SyncApiClient") or ""
        if not imp:
            for l in dependency_ctx.file_content.splitlines():
                if references_sync_api_client(l) and "import" in l:
                    imp = l.strip()
                    break
        synth = ClassInstantiationInfo(
            class_name="SyncApiClient",
            variable_name="sync_api_client",
            import_line=imp,
            instantiation_code="sync_api_client = SyncApiClient()",
            source_file=dependency_ctx.file_path or "",
            is_manual=False,
            is_autogen=True,
            has_sync_api_client=True
        )
        sync_candidates = [synth]

    # Prioritize module-level direct instantiations over inner class attributes,
    # and prefer standard variable name 'client' if available
    if sync_candidates:
        sync_candidates.sort(key=lambda c: (
            bool(c.enclosing_class),
            0 if c.variable_name == "client" else (1 if "sync" in c.variable_name else 2)
        ))
    elif valid_candidates:
        valid_candidates.sort(key=lambda c: (
            bool(c.enclosing_class),
            0 if c.variable_name == "client" else (1 if "sync" in c.variable_name else 2)
        ))

    # Target pool strictly prioritizes SyncApiClient candidates when available
    candidate_pool = sync_candidates if sync_candidates else valid_candidates

    if not candidate_pool:
        if references_sync_api_client(dependency_ctx.file_content):
            return ClassInstantiationInfo(
                class_name="SyncApiClient",
                variable_name="sync_api_client",
                import_line="",
                instantiation_code="sync_api_client = SyncApiClient()",
                has_sync_api_client=True,
                is_autogen=True
            ), "SyncApiClient"
        return None, call.class_name or "AutogenApiClient"

    func_name = call.function_name
    callee_name = call.callee_function

    # 1. Reverse-Engineering Step 1: Find all classes in autogenerated microservice
    # that define func_name or callee_name
    candidate_source_classes = set()
    if call.class_name:
        candidate_source_classes.add(call.class_name.lower())
        candidate_source_classes.add(call.class_name.split(".")[-1].lower())

    for cls_name, methods in class_method_index.items():
        if func_name in methods:
            candidate_source_classes.add(cls_name.lower())
            candidate_source_classes.add(cls_name.split(".")[-1].lower())
        if callee_name and callee_name in methods:
            candidate_source_classes.add(cls_name.lower())
            candidate_source_classes.add(cls_name.split(".")[-1].lower())
        for m in call.caller_chain:
            if m in methods:
                candidate_source_classes.add(cls_name.lower())
                candidate_source_classes.add(cls_name.split(".")[-1].lower())

    # 2. Reverse-Engineering Step 2: Check AST of call.file_path if available
    # to see which class encloses func_name or is instantiated inside func_name
    file_path = call.file_path
    if file_path:
        full_file_path = file_path
        if service_root_path and not os.path.isabs(file_path):
            candidate_full = os.path.join(service_root_path, file_path)
            if os.path.exists(candidate_full):
                full_file_path = candidate_full

        if os.path.exists(full_file_path) and os.path.isfile(full_file_path):
            try:
                with open(full_file_path, "r", encoding="utf-8", errors="replace") as f:
                    tree = ast.parse(f.read(), filename=full_file_path)
                for node in ast.walk(tree):
                    if isinstance(node, ast.ClassDef):
                        for item in node.body:
                            if isinstance(item, (ast.FunctionDef, ast.AsyncFunctionDef)):
                                if item.name in (func_name, callee_name):
                                    candidate_source_classes.add(node.name.lower())
                                    candidate_source_classes.add(node.name.split(".")[-1].lower())
                    elif isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                        if node.name in (func_name, callee_name):
                            # Inspect calls inside function body
                            for subnode in ast.walk(node):
                                if isinstance(subnode, ast.Call):
                                    func_id = None
                                    if isinstance(subnode.func, ast.Name):
                                        func_id = subnode.func.id
                                    elif isinstance(subnode.func, ast.Attribute):
                                        func_id = subnode.func.attr
                                    if func_id:
                                        if func_id.lower() in class_method_index:
                                            candidate_source_classes.add(func_id.lower())
                                            candidate_source_classes.add(func_id.split(".")[-1].lower())
            except Exception:
                pass

    # 3. Reverse-Engineering Step 3: Match source classes against candidates in candidate_pool
    # Priority 3A: Candidate that directly instantiates one of the candidate source classes
    if candidate_source_classes:
        for info in candidate_pool:
            c_name_low = info.class_name.lower()
            c_base_low = info.class_name.split(".")[-1].lower()
            if c_name_low in candidate_source_classes or c_base_low in candidate_source_classes:
                return info, info.class_name

        # Priority 3A.2: Candidate whose sub-attributes link to one of candidate_source_classes
        if class_subattributes_index:
            for info in candidate_pool:
                c_name_low = info.class_name.lower()
                c_base_low = info.class_name.split(".")[-1].lower()
                sub_map = class_subattributes_index.get(c_name_low) or class_subattributes_index.get(c_base_low) or {}
                for target_sub in sub_map.keys():
                    if target_sub in candidate_source_classes:
                        return info, info.class_name

        for info in candidate_pool:
            for sc in candidate_source_classes:
                if re.search(r'\b' + re.escape(sc) + r'\b', info.import_line.lower()):
                    return info, info.class_name

    # Priority 3B: Check if any candidate class has methods in class_method_index
    # matching func_name or callee_name
    for info in candidate_pool:
        c_methods = class_method_index.get(info.class_name.lower()) or class_method_index.get(info.class_name.split(".")[-1].lower())
        if c_methods:
            if func_name in c_methods or (callee_name and callee_name in c_methods):
                return info, info.class_name

    # Priority 3C: Check file stem match
    if file_path:
        file_stem = os.path.splitext(os.path.basename(file_path))[0].lower()
        for info in candidate_pool:
            if file_stem in info.import_line.lower() or file_stem in info.class_name.lower():
                return info, info.class_name

    # Priority 3D: Candidates explicitly referencing SyncApiClient
    for info in candidate_pool:
        if getattr(info, "has_sync_api_client", False):
            return info, info.class_name

    # Priority 3E: Autogen marked candidates
    for info in candidate_pool:
        if info.is_autogen:
            return info, info.class_name

    # Priority 3F: First candidate in candidate_pool
    return candidate_pool[0], candidate_pool[0].class_name


def generate_function_call_example(
    call: EndpointCall,
    dependency_ctx: Optional[DependencyContext] = None,
    service_root_path: str = "",
    manual_service_path: str = "",
    known_manual_classes: Optional[Set[str]] = None,
    known_autogen_classes: Optional[Set[str]] = None,
    class_method_index: Optional[Dict[str, Set[str]]] = None,
    class_subattributes_index: Optional[Dict[str, Dict[str, str]]] = None,
    sync_api_client_vars: Optional[Dict[str, str]] = None,
    function_origin_map: Optional[Dict[str, str]] = None
) -> Dict[str, Any]:
    """
    Generate an example of function call strictly using the dependencies
    of the autogenerated microservice (never manual microservice dependencies).
    Follows the 3-step approach:
    1. Retrieve the class name from which the endpoint function originates.
    2. In class SyncApiClient, retrieve the variable name that instantiates this class.
    3. Include this variable name in the function call path (e.g. response = client.views.get_product_views(...)).
    """
    func_name = call.function_name
    file_path = call.file_path or "service.py"
    dep_file = dependency_ctx.file_path if dependency_ctx else None

    # Ensure class_method_index is available
    if class_method_index is None:
        class_method_index = build_class_method_index(dir_path=service_root_path, calls=[call])

    # Ensure class_subattributes_index is available
    if class_subattributes_index is None:
        dep_reg = None
        if dependency_ctx:
            dep_key = os.path.splitext(os.path.basename(dependency_ctx.file_path or "service"))[0].lower()
            dep_reg = {dep_key: dependency_ctx}
        class_subattributes_index = build_class_subattributes_index(
            dir_path=service_root_path,
            dependency_registry=dep_reg
        )

    chosen_info: Optional[ClassInstantiationInfo] = None
    class_name = call.class_name or "AutogenApiClient"

    if dependency_ctx:
        chosen_info, resolved_class = reverse_engineer_autogen_dependency(
            call=call,
            dependency_ctx=dependency_ctx,
            class_method_index=class_method_index,
            manual_service_path=manual_service_path,
            known_manual_classes=known_manual_classes,
            service_root_path=service_root_path,
            class_subattributes_index=class_subattributes_index
        )
        if resolved_class:
            class_name = resolved_class

    imports = []
    class_instantiation = ""
    var_name = "client"

    if chosen_info:
        var_name = chosen_info.variable_name or "client"
        class_name = chosen_info.class_name
        if chosen_info.import_line:
            imports.append(chosen_info.import_line)
        class_instantiation = chosen_info.instantiation_code
    else:
        # Fallback to standard autogen module import (NEVER manual)
        mod_name = os.path.splitext(os.path.basename(file_path))[0]
        if service_root_path:
            pkg_name = os.path.basename(os.path.normpath(service_root_path))
            import_str = f"from {pkg_name}.{mod_name} import {class_name}"
        else:
            import_str = f"from {mod_name} import {class_name}"
        imports.append(import_str)
        class_instantiation = f"{var_name} = {class_name}(token=\"YOUR_API_TOKEN\")"

    # Add helper imports/comments if factory function or container exists
    target_class_for_factory = chosen_info.class_name if chosen_info else class_name
    factory_name = None
    if dependency_ctx and target_class_for_factory:
        for c_name, f_call in dependency_ctx.factory_functions.items():
            if c_name.lower() == target_class_for_factory.lower() or c_name.split(".")[-1].lower() == target_class_for_factory.lower():
                if not any(kw in f_call.lower() for kw in ["manual", "legacy", "old"]):
                    factory_name = f_call
                    break

    if factory_name:
        class_instantiation = f"# Option via fabrique autogénérée:\n{var_name} = {factory_name}\n# Ou instanciation directe:\n{class_instantiation}"
    elif chosen_info and chosen_info.enclosing_class:
        enc = chosen_info.enclosing_class
        class_instantiation += f"\n# Ou via conteneur {enc}:\n# deps = {enc}()\n# {var_name} = deps.{chosen_info.variable_name}"

    # Check parameter types and add typing imports if needed
    needed_types = []
    for p in call.function_params:
        ann = p.type_annotation or ""
        for t in ["List", "Dict", "Optional", "Any", "Union", "Tuple"]:
            if t in ann and t not in needed_types:
                needed_types.append(t)
    if needed_types:
        imports.insert(0, f"from typing import {', '.join(needed_types)}")

    # -------------------------------------------------------------------------
    # 3-Step Approach:
    # 1. Lors de la récupération du endpoint du microservice autogénéré,
    #    récupérer le nom de la classe dont la fonction est issue.
    # 2. Dans la classe SyncApiClient, récupérer le nom de variable qui instancie cette classe.
    # 3. C'est ce nom de variables qui doit se retrouver dans le path de l'appel de la fonction.
    # -------------------------------------------------------------------------

    # Step 1: Récupérer le nom de la classe dont la fonction est issue
    origin_class = getattr(call, "origin_class", None) or call.class_name
    if not origin_class or origin_class.lower() in ("autogenapiclient", "baseclient", "apiclient", "none"):
        if function_origin_map:
            origin_class = (
                function_origin_map.get(func_name) or
                function_origin_map.get(func_name.lower()) or
                function_origin_map.get(call.callee_function or "") or
                origin_class
            )
        elif service_root_path:
            try:
                from .parser import get_function_origin_class_map
                f_map = get_function_origin_class_map(dir_path=service_root_path)
                origin_class = (
                    f_map.get(func_name) or
                    f_map.get(func_name.lower()) or
                    f_map.get(call.callee_function or "") or
                    origin_class
                )
            except Exception:
                pass

    # Step 2: Dans la classe SyncApiClient, récupérer le nom de variable qui instancie cette classe
    if sync_api_client_vars is None:
        dep_reg = None
        if dependency_ctx:
            dep_key = os.path.splitext(os.path.basename(dependency_ctx.file_path or "service"))[0].lower()
            dep_reg = {dep_key: dependency_ctx}
        sync_api_client_vars = get_sync_api_client_variable_map(
            dir_path=service_root_path,
            dependency_registry=dep_reg
        )

    sub_var = None
    if origin_class and sync_api_client_vars:
        orig_low = origin_class.lower()
        orig_base_low = origin_class.split(".")[-1].lower()
        if orig_low not in ("syncapiclient", "syncclient", "client"):
            sub_var = (
                sync_api_client_vars.get(origin_class) or
                sync_api_client_vars.get(orig_low) or
                sync_api_client_vars.get(orig_base_low)
            )
            if not sub_var:
                stem = re.sub(r'^(sync|syn|async)', '', orig_base_low)
                stem = re.sub(r'(api|client|service|controller)$', '', stem)
                if stem:
                    sub_var = (
                        sync_api_client_vars.get(stem) or
                        sync_api_client_vars.get(stem + "api") or
                        sync_api_client_vars.get("sync" + stem + "api") or
                        sync_api_client_vars.get("syn" + stem + "api")
                    )
                if not sub_var:
                    for k, v in sync_api_client_vars.items():
                        if k in orig_base_low or orig_base_low in k:
                            sub_var = v
                            break

    # Step 3: C'est ce nom de variables qui doit se retrouver dans le path de l'appel de la fonction
    if sub_var:
        call_path_prefix = sub_var
        implementing_class = origin_class
        call_target = f"{var_name}.{sub_var}"
    else:
        # Fallback to resolve_function_call_path if BFS finds a deeper chain
        call_path_prefix, implementing_class = resolve_function_call_path(
            root_class=chosen_info.class_name if chosen_info else class_name,
            func_name=func_name,
            callee_name=call.callee_function,
            target_class=origin_class or call.class_name,
            class_method_index=class_method_index,
            class_subattributes_index=class_subattributes_index
        )
        call_target = f"{var_name}.{call_path_prefix}" if call_path_prefix else var_name

    # Build Call Parameters Example
    call_args = []
    for p in call.function_params:
        if p.name in ("self", "cls"):
            continue
        val = format_example_value(p)
        call_args.append(f"{p.name}={val}")

    if len(call_args) <= 2 and sum(len(a) for a in call_args) < 50:
        call_str = f"response = {call_target}.{func_name}({', '.join(call_args)})"
    else:
        formatted_args = ",\n    ".join(call_args)
        call_str = f"response = {call_target}.{func_name}(\n    {formatted_args}\n)"

    # Assemble Complete Snippet
    snippet_parts = [
        "# ==================================================",
        f"# Exemple d'appel pour la fonction autogénérée: {call_target}.{func_name}()",
        f"# Endpoint: [{call.http_method}] {call.normalized_endpoint}",
    ]
    if dep_file and chosen_info:
        snippet_parts.append(f"# Dépendance autogénérée issue de: {os.path.basename(dep_file)}")
    snippet_parts.append("# ==================================================\n")

    snippet_parts.append("# 1. Imports nécessaires (microservice autogénéré)")
    snippet_parts.extend(imports)
    snippet_parts.append("\n# 2. Initialisation de la dépendance autogénérée")
    snippet_parts.append(class_instantiation)
    snippet_parts.append("\n# 3. Appel de la fonction du microservice autogénéré")
    snippet_parts.append(call_str)
    snippet_parts.append("print(f\"Résultat reçu: {response}\")")

    full_code = "\n".join(snippet_parts)

    return {
        "function_name": func_name,
        "class_name": class_name,
        "implementing_class": implementing_class,
        "call_path": call_path_prefix,
        "call_target": call_target,
        "variable_name": var_name,
        "dependency_file": os.path.basename(dep_file) if (dep_file and chosen_info) else None,
        "imports": imports,
        "instantiation": class_instantiation,
        "call_snippet": call_str,
        "full_code": full_code
    }

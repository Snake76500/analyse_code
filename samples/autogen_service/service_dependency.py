"""
Service Dependency Declaration for Autogenerated Microservice.
This file declares class dependencies for both manual and autogenerated services.
The analyzer must strictly use ONLY the autogenerated microservice dependencies for example calls.
"""
from typing import Optional
from manual_service.service import ManualServiceClient
from autogen_service.service import AutogenApiClient


class ServiceDependencies:
    """
    Class container declaring service client dependencies (legacy manual and autogen).
    """

    def __init__(self, token: Optional[str] = None, api_key: Optional[str] = None):
        # Dépendance microservice manuel (legacy - NE DOIT PAS être utilisée dans les exemples)
        self.manual_client = ManualServiceClient(api_key=api_key or "MANUAL_DEV_KEY_123")
        # Dépendance microservice autogénéré (DOIT être utilisée pour les exemples)
        self.autogen_client = AutogenApiClient(token=token or "PROD_AUTH_TOKEN_XYZ")

    def get_manual_client(self) -> ManualServiceClient:
        """Returns legacy manual service client."""
        return self.manual_client

    def get_autogen_client(self) -> AutogenApiClient:
        """Returns autogenerated API client."""
        return self.autogen_client


# Déclaration directe pour le client manuel (legacy)
manual_client = ManualServiceClient(api_key="MANUAL_DEV_KEY_123")

# Déclaration directe pour le client autogénéré
default_client = AutogenApiClient(token="PROD_AUTH_TOKEN_XYZ")


def get_manual_service(api_key: str = "MANUAL_DEV_KEY_123") -> ManualServiceClient:
    """Factory function for the manual microservice (legacy)."""
    return ManualServiceClient(api_key=api_key)


def create_api_client(token: str = "PROD_AUTH_TOKEN_XYZ") -> AutogenApiClient:
    """Factory function to instantiate the autogenerated API client."""
    return AutogenApiClient(token=token)

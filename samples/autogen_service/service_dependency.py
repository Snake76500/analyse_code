"""
Service Dependency Declaration for Autogenerated Microservice.
This file declares class dependencies, required tokens/parameters, and client factories.
"""
from typing import Optional
from autogen_service.service import AutogenApiClient


class ServiceDependencies:
    """
    Class container declaring the service client dependency configuration.
    """

    def __init__(self, token: Optional[str] = None):
        self.token = token or "PROD_AUTH_TOKEN_XYZ"
        self.client = AutogenApiClient(token=self.token)

    def get_client(self) -> AutogenApiClient:
        """Returns initialized client instance."""
        return self.client


# Default client declaration for direct usage
default_client = AutogenApiClient(token="PROD_AUTH_TOKEN_XYZ")


def create_api_client(token: str = "PROD_AUTH_TOKEN_XYZ") -> AutogenApiClient:
    """Factory function to instantiate the autogenerated API client."""
    return AutogenApiClient(token=token)
